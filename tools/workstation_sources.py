"""Persistent source catalog for the pinned Replay workstation.

The catalog is an identity view over recovered inputs.  Disassembler text is
kept separate from compiler assembly and from authored C++; pseudocode is never
fed to the compiler.  Function identity, not an RVA entered by the user, is the
association key for edits.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import sqlite3
import struct
import threading
from contextlib import closing
from pathlib import Path
from typing import Any

import source_catalog


DEFAULT_SQLITE = source_catalog.database_path()
SCHEMA = 1


def _is_opaque_name(name: str) -> bool:
    """Recognize autogenerated address labels without rejecting meaningful names."""
    from recovered_cpp_names import is_generated_name
    return is_generated_name(name)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _sqlite_file_signature(path: Path):
    """Include SQLite commit markers so fast commits invalidate cached names.

    The main change counter is documented in SQLite file format sections 1.3.6
    and 1.3.16; WAL commit framing is documented at https://sqlite.org/walformat.html.
    """
    signature = []
    for candidate in (path, Path(str(path) + "-wal"), Path(str(path) + "-shm")):
        try:
            stat = candidate.stat()
            content_marker = b""
            with candidate.open("rb") as stream:
                if candidate == path:
                    # SQLite's change counter and version-valid-for number
                    # advance on committed rollback-journal transactions even
                    # when filesystem timestamp precision hides the update.
                    header = stream.read(100)
                    content_marker = header[24:28] + header[92:96]
                elif candidate.name.endswith("-wal"):
                    # A WAL commit may leave the main database header alone.
                    # Include its epoch header and newest complete frame header.
                    wal_header = stream.read(32)
                    frame_marker = b""
                    stream.seek(0, os.SEEK_END)
                    wal_size = stream.tell()
                    if len(wal_header) == 32 and len(wal_header) >= 12:
                        page_size = int.from_bytes(wal_header[8:12], "big")
                        if page_size == 1:
                            page_size = 65536
                        frame_size = 24 + page_size
                        complete_frames = ((wal_size - 32) // frame_size
                                           if page_size and wal_size >= 32 + frame_size else 0)
                        if complete_frames:
                            stream.seek(32 + (complete_frames - 1) * frame_size)
                            frame_marker = stream.read(24)
                    content_marker = wal_header + frame_marker
                else:
                    # The WAL index change counter advances as frames commit.
                    content_marker = stream.read(48)
            signature.append((candidate.name, True, stat.st_size, stat.st_mtime_ns,
                              getattr(stat, "st_ctime_ns", None), getattr(stat, "st_ino", None),
                              content_marker))
        except OSError:
            signature.append((candidate.name, False, None, None, None, None, b""))
    return tuple(signature)


def _atomic_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    temporary.replace(path)


def verify_assembly_coff(identity, obj):
    """Check the symbol and COFF unwind extent for one editor assembly unit."""
    definitions = [s for s in obj["symbols"].values()
                   if s["name"] == identity and s["section"] > 0 and s["storage"] == 2]
    if len(definitions) != 1 or definitions[0]["value"] != 0:
        raise ValueError(f"Assembly must define one external {identity} symbol at code offset zero")
    definition = definitions[0]
    code = obj["sections"][definition["section"]-1]
    if not code["flags"] & 0x20:
        raise ValueError(f"Assembly function {identity} did not compile into executable code")
    pdata = next((s for s in obj["sections"] if s["name"] == ".pdata" and s["data"]), None)
    xdata = next((s for s in obj["sections"] if s["name"] == ".xdata" and s["data"]), None)
    if pdata is None or xdata is None or len(pdata["data"]) != 12:
        raise ValueError("Assembly must emit exactly one real COFF .pdata/.xdata unwind record")
    relocations = {offset: obj["symbols"][symbol_index]
                   for offset, symbol_index, _kind in pdata["relocations"]}
    begin, end, unwind = (relocations.get(n) for n in (0, 4, 8))
    begin_addend, end_addend, _ = struct.unpack("<III", pdata["data"])
    if (begin is None or end is None or unwind is None or
            begin["section"] != definition["section"] or end["section"] != definition["section"] or
            begin_addend != definition["value"] or end_addend != definition["value"] + len(code["data"]) or
            unwind["section"] <= 0 or obj["sections"][unwind["section"]-1]["name"] != ".xdata"):
        raise ValueError("COFF unwind begin/end must cover the selected function and point to .xdata")
    from workstation_seh import verify_handler_object
    handler = verify_handler_object(obj)
    return {"symbol": identity, "code_size": len(code["data"]), "pdata_size": len(pdata["data"]),
            "xdata_size": len(xdata["data"]), "unwind_begin": begin_addend, "unwind_end": end_addend,
            "handler_data": handler}


class SourceWorkspace:
    """Browse and revise sources by catalog identity.

    ``cache_root`` holds the source-workstation catalog/revisions.  Compilable
    C++ and assembly units are placed in the project where the existing build
    can consume them; source identities are resolved against the generated
    catalog and PE-derived function index on every build.
    """

    def __init__(self, project_root, cache_root, sqlite_path=None):
        self.root = Path(project_root).resolve()
        self.cache_root = Path(cache_root).resolve()
        self.sqlite_path = Path(sqlite_path or os.environ.get("REPLAY_SQLITE") or DEFAULT_SQLITE).expanduser().resolve()
        self.generated = self.root / "generated"
        self.catalog_path = self.generated / "function-catalog.json"
        self.manifest_path = self.cache_root / "workstation-sources.json"
        self.units_path = self.root / "source-workstation" / "units.json"
        self.user_functions_path = self.root / "source-workstation" / "user-functions.json"
        self._catalog: dict[str, Any] | None = None
        self._sqlite_text: dict[str, dict[str, str]] | None = None
        self._native_index = None
        self._native_sources = None
        self._instruction_cache = None
        self._sqlite_signature = None
        self._sqlite_names = None
        self._decompiler_names = {}
        self._quarantined_rvas = set()
        self._sqlite_names_signature = None
        self._catalog_sql_signature = None
        self._sorted_catalog_rows = None
        self._cpp_index = None
        self._cpp_index_lock = threading.Lock()

    def cpp_index(self):
        if self._cpp_index is None:
            with self._cpp_index_lock:
                if self._cpp_index is None:
                    from workstation_cpp_sources import CppSourceIndex
                    self._cpp_index = CppSourceIndex(self)
        return self._cpp_index

    def cpp_symbols(self, rows):
        # Build the name/alias lookup once, never reload the catalog per function.
        self._matching_rows('')
        lookup = self._identity_lookup
        keywords = set('alignas alignof and and_eq asm auto bitand bitor bool break case catch char char8_t char16_t char32_t class compl concept const consteval constexpr constinit const_cast continue co_await co_return co_yield decltype default delete do double dynamic_cast else enum explicit export extern false float for friend goto if inline int long mutable namespace new noexcept not not_eq nullptr operator or or_eq private protected public register reinterpret_cast requires return short signed sizeof static static_assert static_cast struct switch template this thread_local throw true try typedef typeid typename union unsigned using virtual void volatile wchar_t while xor xor_eq'.split())
        result = {}
        from recovered_cpp_names import function_name
        image_base = json.loads((self.generated / 'manifest.json').read_text())['image_base']
        for row in rows:
            name = row.get('name', '')
            owners = {candidate['id'] for candidate in lookup.get(name, [])}
            valid = (re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', name) and not _is_opaque_name(name)
                     and name not in keywords and owners == {row['id']})
            result[row['id']] = name if valid else function_name(row['rva'], image_base)
        return result

    def _load_catalog(self):
        catalog = json.loads(self.catalog_path.read_text(encoding="utf-8"))
        manifest = json.loads((self.generated / "manifest.json").read_text(encoding="utf-8"))
        if catalog.get("image_sha256") != manifest.get("input_sha256"):
            raise ValueError("Function catalog is not from this generated Replay image")
        self._catalog = catalog
        self._text_bounds = [(section['rva'], section['rva'] + section['virtual_size'])
                             for section in manifest.get('sections', []) if section.get('flags', 0) & 0x20]
        return catalog

    def _rows(self):
        catalog = self._catalog or self._load_catalog()
        sqlite_rows = self._entry_names()
        if self._sorted_catalog_rows is None or self._catalog_sql_signature != self._sqlite_names_signature:
            functions = []
            for original in catalog["functions"]:
                if original.get('quarantined') or original['rva'] in self._quarantined_rvas:
                    continue
                row = dict(original)
                row.pop('decompiler_name', None)
                row.pop('decompiler_idb_sha256', None)
                row.update(self._decompiler_names.get(row['rva'], {}))
                raw_name = row.get("name", "")
                sql = sqlite_rows.get(f"{row['rva']:x}", {})
                sql_name = sql
                if sql_name:
                    row["aliases"] = sorted(set(row.get("aliases", [])) | {sql_name})
                    if not _is_opaque_name(sql_name):
                        row["name"] = sql_name
                    elif not _is_opaque_name(raw_name):
                        row["name"] = raw_name
                functions.append(row)
            known = {row['rva'] for row in functions}
            for key, name in sqlite_rows.items():
                rva = int(key, 16)
                if rva not in known and any(begin <= rva < end for begin, end in self._text_bounds):
                    functions.append({'id': source_catalog.stable_id(catalog['image_sha256'], rva),
                                      'name': name, 'aliases': [], 'rva': rva, 'kind': 'function',
                                      'provenance': 'new SQLite function; native ownership is checked at compilation',
                                      **self._decompiler_names.get(rva, {})})
            rows = functions + [dict(row) for row in catalog.get("symbols", [])]
            self._sorted_catalog_rows = sorted(rows, key=lambda r: (self._display_name(r).casefold(), r["id"]))
            self._catalog_sql_signature = self._sqlite_names_signature
        return self._sorted_catalog_rows

    def _display_name(self, row):
        name = row.get("name", "")
        if row.get("kind", "function") == "function" and (not name or _is_opaque_name(name)):
            from recovered_cpp_names import function_name
            image_base = (self._catalog or {}).get('image_base', 0x140000000)
            return function_name(row['rva'], image_base)
        if row.get('kind', 'function') != 'function':
            from recovered_cpp_names import DATA_PLACEHOLDER, global_name
            if DATA_PLACEHOLDER.fullmatch(name):
                return global_name(row['rva'], (self._catalog or {}).get('image_base', 0x140000000))
        return name

    def _catalog_symbol(self, rva):
        matches = [row for row in self._rows() if row["rva"] == rva]
        function_matches = [row for row in matches if row.get("kind", "function") == "function"]
        candidates = function_matches or matches
        identities = {row["id"] for row in candidates}
        if len(identities) != 1:
            raise ValueError(f"Recovered assembly reference {rva:#x} has no unique stable catalog identity")
        return next(iter(identities))

    def _entry_names(self):
        signature = _sqlite_file_signature(self.sqlite_path)
        if self._sqlite_names is not None and signature == self._sqlite_names_signature:
            return self._sqlite_names
        if not self.sqlite_path.is_file():
            self._sqlite_names = {}
            self._decompiler_names = {}
            self._quarantined_rvas = set()
            self._sqlite_names_signature = signature
            return self._sqlite_names
        manifest = json.loads((self.generated / "manifest.json").read_text(encoding="utf-8"))
        image_base = int(manifest["image_base"])
        names = {}
        with closing(sqlite3.connect(source_catalog.readonly_uri(self.sqlite_path), uri=True)) as db:
            db.execute("BEGIN")
            catalog = self._catalog or self._load_catalog()
            expected_md5 = catalog.get('database_program_md5')
            if not expected_md5 and db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='replay_ida_export_function_names'").fetchone():
                expected_md5 = json.loads((self.generated / 'ida-code-report.json').read_text())['input_md5']
            export_names = source_catalog.decompiler_function_names(db, catalog['image_sha256'], expected_md5)
            quarantine = source_catalog.function_quarantine(db, image_base)
            self._quarantined_rvas = {row['rva'] for row in quarantine.values()}
            columns = {row[1] for row in db.execute("PRAGMA table_info(functions)")}
            if "address" not in columns:
                raise ValueError("Replay SQLite functions table has no address column")
            if "name" in columns:
                seen = set()
                for address, name in db.execute('SELECT "address","name" FROM functions'):
                    try:
                        rva = source_catalog.parse_integer(address, "address") - image_base
                    except (TypeError, ValueError):
                        continue
                    seen.add(rva)
                    if name and rva not in self._quarantined_rvas:
                        names[f"{rva:x}"] = str(name)
                if export_names.keys() - seen:
                    raise ValueError('Decompiler name provenance refers to an absent function')
        self._sqlite_names = names
        self._decompiler_names = export_names
        self._sqlite_names_signature = signature
        return names

    def _by_identity(self, identity: str, kind: str | None = None):
        rows = self._matching_rows(identity)
        if kind == "function":
            rows = [r for r in rows if r.get("kind", "function") == "function"]
        if kind == "symbol":
            rows = [r for r in rows if r.get("kind") != "function"]
        if len(rows) != 1:
            raise KeyError("Unknown or ambiguous source identity; select a unique catalog ID")
        return rows[0]

    def _matching_rows(self, identity):
        rows = self._rows()
        if getattr(self, '_identity_rows', None) is not rows:
            lookup = {}
            from recovered_cpp_names import function_name, global_name
            image_base = json.loads((self.generated / 'manifest.json').read_text())['image_base']
            for row in rows:
                automatic = (function_name if row.get('kind', 'function') == 'function' else global_name)(row['rva'], image_base)
                for name in {row['id'], row.get('name', ''), automatic, *row.get('aliases', [])} - {''}:
                    lookup.setdefault(name, []).append(row)
            self._identity_lookup, self._identity_rows = lookup, rows
        return self._identity_lookup.get(identity, [])

    def _entry_text(self):
        signature = _sqlite_file_signature(self.sqlite_path)
        if self._sqlite_text is not None and signature == self._sqlite_signature:
            return self._sqlite_text
        result: dict[str, dict[str, str]] = {}
        image_base = int(json.loads((self.generated / "manifest.json").read_text())["image_base"])
        db = sqlite3.connect(source_catalog.readonly_uri(self.sqlite_path), uri=True)
        try:
            # The IDA database is evidence only. Do not mutate it through this API.
            db.execute("BEGIN")
            columns = {row[1] for row in db.execute("PRAGMA table_info(functions)")}
            if "address" not in columns:
                raise ValueError("Replay SQLite functions table has no address column")
            selected = ["address"] + [c for c in ("assembly", "clean_assembly", "pseudocode", "clean_pseudo", "prototype", "name") if c in columns]
            query = "SELECT " + ",".join('"' + c + '"' for c in selected) + " FROM functions"
            for values in db.execute(query):
                row = dict(zip(selected, values))
                try:
                    rva = source_catalog.parse_integer(row["address"], "address") - image_base
                except (TypeError, ValueError):
                    continue
                result[f"{rva:x}"] = {k: str(v) for k, v in row.items() if k != "address" and v is not None}
            # Newer IDA override tables are kept as a separate pseudocode basis.
            tables = {row[0] for row in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}
            if "replay_ida_function_text" in tables:
                for rva, pseudo in db.execute("SELECT function_rva,pseudocode FROM replay_ida_function_text"):
                    try:
                        key = f"{int(rva, 0):x}" if isinstance(rva, str) else f"{int(rva):x}"
                    except (TypeError, ValueError):
                        continue
                    if pseudo:
                        result.setdefault(key, {})["ida_pseudocode_override"] = str(pseudo)
        finally:
            db.close()
        self._sqlite_text = result
        self._sqlite_signature = signature
        return result

    def _state(self):
        if not self.manifest_path.exists():
            state = {"schema": SCHEMA, "image_sha256": (self._catalog or self._load_catalog())["image_sha256"], "sources": {}}
        else:
            state = json.loads(self.manifest_path.read_text(encoding="utf-8"))
            if state.get("schema") != SCHEMA or state.get("image_sha256") != (self._catalog or self._load_catalog())["image_sha256"]:
                raise ValueError("Workstation revisions belong to a different Replay image or schema")
        self._restore_persisted_user_functions(state)
        self._restore_persisted_compiler_sources(state)
        return state

    def _restore_persisted_compiler_sources(self, state):
        """Hydrate authored catalog C++ and assembly revisions from build metadata."""
        sources = state.setdefault("sources", {})
        if not isinstance(sources, dict):
            raise ValueError("Cached source metadata is malformed")
        units = self._assembly_unit_state().get("units", [])
        if not isinstance(units, list):
            raise ValueError("Compiled workstation units have no valid unit list")
        for unit in units:
            if not isinstance(unit, dict) or unit.get("kind") not in ("cpp", "assembly"):
                continue
            identity = unit.get("function_id")
            if not isinstance(identity, str):
                raise ValueError("Persisted compiler source has no catalog function identity")
            row = self._by_identity(identity, "function")
            if unit["kind"] == "cpp":
                persisted = self._persisted_cpp_binding(identity)
                if persisted is None:
                    continue
                relative, language = persisted["relative"], unit.get("language", "cpp")
                symbol, digest = unit["symbol"], persisted["revision"]
                provenance = {"basis": "persisted source-workstation C++ association",
                              "source_identity": identity,
                              "target_catalog_image_sha256": state["image_sha256"],
                              "target_rva_derived_by_catalog": row["rva"],
                              "symbol": symbol,
                              "abi_confidence": "unverified; authored declaration is not inferred"}
            else:
                persisted = self._persisted_assembly_binding(identity)
                if persisted is None:
                    continue
                relative, language = persisted["relative"], unit.get("language", "x86_64-coff-asm")
                symbol, digest = None, persisted["revision"]
                provenance = {"basis": "persisted source-workstation assembly association",
                              "source_identity": identity,
                              "target_catalog_image_sha256": state["image_sha256"],
                              "target_rva_derived_by_catalog": row["rva"]}
            binding = {"path": relative.as_posix(), "language": language,
                       "revision": digest, "sha256": digest, "compilable": True,
                       "function_id": identity if unit["kind"] == "cpp" else None,
                       "symbol": symbol, "provenance": provenance}
            row_sources = sources.setdefault(identity, {})
            prior = row_sources.get(unit["kind"])
            if prior is not None:
                if any(prior.get(key) != binding.get(key)
                       for key in ("path", "language", "revision", "sha256", "function_id", "symbol")):
                    raise ValueError("Cached and persisted compiler source revisions conflict")
            else:
                row_sources[unit["kind"]] = binding

    def _restore_persisted_user_functions(self, state):
        """Rehydrate cache-visible helper sources from the portable build manifest."""
        users = self._user_functions().get("functions")
        if not isinstance(users, dict):
            raise ValueError("New C++ units have no valid functions map")
        cached = state.setdefault("user_sources", {})
        if not isinstance(cached, dict):
            raise ValueError("Cached user-source metadata is malformed")
        for identity, row in users.items():
            if not isinstance(row, dict):
                raise ValueError("Persisted user-function metadata is malformed")
            name, relative, digest = row.get("name"), row.get("path"), row.get("sha256")
            revision = row.get("revision")
            expected_identity = ("user_" + hashlib.sha256(name.encode("utf-8")).hexdigest()[:16]
                                 if isinstance(name, str) else None)
            if (identity != expected_identity or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name or "") or
                    relative != f"src/workstation_{identity}.{'c' if row.get('language') == 'c' else 'cpp'}" or
                    not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest) or
                    revision != digest):
                raise ValueError("Persisted user-function identity or revision metadata is malformed")
            path = (self.root / relative).resolve()
            if not path.is_relative_to(self.root / "src") or not path.is_file():
                raise ValueError("Persisted user C++ source is missing or outside src/")
            content = path.read_bytes()
            if sha256(content) != digest:
                raise ValueError("Persisted user C++ source revision/hash mismatch")
            try:
                text = content.decode("utf-8")
            except UnicodeDecodeError as error:
                raise ValueError("Persisted user C++ source is not UTF-8") from error
            if not re.search(rf"\b{re.escape(name)}\s*\(", text):
                raise ValueError(f"Persisted user C++ source no longer defines {name}")
            restored = {"name": name, "path": relative, "revision": digest, "sha256": digest, 'language': row.get('language', 'cpp'),
                        "provenance": {"basis": "persisted source-workstation user-function binding",
                                       "target": "new linked symbol; no native function identity",
                                       "abi_confidence": "authored by user; no native prototype inferred"}}
            prior = cached.get(identity)
            if prior is not None and any(prior.get(key) != restored[key]
                                         for key in ("name", "path", "revision", "sha256")):
                raise ValueError("Cached and persisted user-function identities conflict")
            if prior is None:
                cached[identity] = restored

    def _persisted_cpp_binding(self, identity):
        """Load and verify one catalog C++ source persisted for compiler input."""
        document = self._assembly_unit_state()
        units = document.get("units")
        if not isinstance(units, list):
            raise ValueError("Compiled workstation units have no valid unit list")
        matches = [unit for unit in units
                   if isinstance(unit, dict) and unit.get("kind") == "cpp"
                   and unit.get("function_id") == identity]
        if len(matches) > 1:
            raise ValueError("Catalog function has multiple persisted C++ source bindings")
        if not matches:
            return None
        unit = matches[0]
        source, symbol, digest = unit.get("source"), unit.get("symbol"), unit.get("sha256")
        if (not isinstance(source, str) or not isinstance(symbol, str) or not symbol or
                not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest) or
                unit.get("revision") != digest):
            raise ValueError("Persisted catalog C++ source metadata is malformed")
        relative = Path(source)
        expected_suffix = ".c" if unit.get("language") == "c" else ".cpp"
        if relative.is_absolute() or ".." in relative.parts or relative.suffix != expected_suffix:
            raise ValueError("Persisted catalog C++ source path is invalid")
        path = (self.root / relative).resolve()
        if not path.is_relative_to(self.root / "src") or not path.is_file():
            raise ValueError("Persisted catalog C++ source is missing or outside src/")
        content = path.read_bytes()
        if sha256(content) != digest:
            raise ValueError("Persisted catalog C++ source revision/hash mismatch")
        try:
            text = content.decode("utf-8")
        except UnicodeDecodeError as error:
            raise ValueError("Persisted catalog C++ source is not UTF-8") from error
        return {"unit": unit, "relative": relative, "path": path, "content": text,
                "revision": digest}

    def _persisted_assembly_binding(self, identity):
        """Load and verify one assembly revision persisted for compiler input."""
        document = self._assembly_unit_state()
        units = document.get("units")
        if not isinstance(units, list):
            raise ValueError("Compiled workstation units have no valid unit list")
        matches = [unit for unit in units
                   if isinstance(unit, dict) and unit.get("kind") == "assembly"
                   and unit.get("function_id") == identity]
        if len(matches) > 1:
            raise ValueError("Catalog function has multiple persisted assembly source bindings")
        if not matches:
            return None
        unit = matches[0]
        source, digest = unit.get("source"), unit.get("sha256")
        expected = f"source-workstation/assembly/{identity}.s"
        if (source != expected or not isinstance(digest, str) or
                not re.fullmatch(r"[0-9a-f]{64}", digest) or unit.get("revision") != digest):
            raise ValueError("Persisted assembly source identity or revision metadata is malformed")
        path = (self.root / source).resolve()
        if not path.is_relative_to(self.root / "source-workstation" / "assembly") or not path.is_file():
            raise ValueError("Persisted assembly source is missing or outside its managed directory")
        content = path.read_bytes()
        if sha256(content) != digest:
            raise ValueError("Persisted assembly source revision/hash mismatch")
        try:
            text = content.decode("utf-8")
        except UnicodeDecodeError as error:
            raise ValueError("Persisted assembly source is not UTF-8") from error
        return {"unit": unit, "relative": Path(source), "path": path, "content": text,
                "revision": digest}

    def _assembly_unit_state(self):
        if not self.units_path.exists():
            return {"schema": 1, "image_sha256": (self._catalog or self._load_catalog())["image_sha256"], "units": []}
        document = json.loads(self.units_path.read_text(encoding="utf-8"))
        if document.get("image_sha256") != (self._catalog or self._load_catalog())["image_sha256"]:
            raise ValueError("Compiled workstation units belong to another Replay image")
        return document

    def _bound_cpp_units(self):
        path = self.root / "source-units.json"
        if not path.exists():
            return []
        document = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(document.get("units"), list):
            raise ValueError("source-units.json has no valid C++ unit list")
        return document["units"]

    def _cpp_mapping(self, row):
        """Return the authored C++ linkage name and source for one catalog function.

        A unique ordinary catalog name is the convenient spelling. Opaque,
        invalid, or colliding names use the automatically derived func_ name.
        Existing explicit source-unit bindings retain their authored path and
        symbol unchanged.
        """
        bound = [unit for unit in self._bound_cpp_units()
                 if unit.get("function_id") == row["id"]]
        if len(bound) > 1:
            raise ValueError("Catalog function has multiple explicit C++ source bindings")
        if bound:
            unit = bound[0]
            return unit["symbol"], Path(unit["source"])
        persisted = [unit for unit in self._assembly_unit_state().get("units", [])
                     if unit.get("kind") == "cpp" and unit.get("function_id") == row["id"]]
        if len(persisted) > 1:
            raise ValueError("Catalog function has multiple persisted C++ source bindings")
        if persisted:
            unit = persisted[0]
            return unit["symbol"], Path(unit["source"])
        saved = self._state().get("sources", {}).get(row["id"], {}).get("cpp")
        if saved:
            symbol = saved.get("symbol")
            relative = Path(saved.get("path", ""))
            if (saved.get("function_id", row["id"]) != row["id"] or not symbol or
                    not relative.as_posix().startswith("src/") or
                    relative.as_posix() not in (f"src/workstation_{row['id']}.cpp", f"src/workstation_{row['id']}.c")):
                raise ValueError("Saved C++ identity/name/source mapping is malformed")
            owners = self._matching_rows(symbol)
            if any(candidate["id"] != row["id"] for candidate in owners):
                raise ValueError("Saved C++ symbol is now claimed by another catalog function")
            return symbol, relative
        symbol = self.cpp_symbols([row])[row['id']]
        return symbol, Path("src") / f"workstation_{row['id']}.cpp"

    def _write_cpp_unit(self, identity, symbol, relative, digest, language):
        document = self._assembly_unit_state()
        units = document.get("units")
        if not isinstance(units, list):
            raise ValueError("Compiled workstation units have no valid unit list")
        matching = [unit for unit in units
                    if unit.get("kind") == "cpp" and unit.get("function_id") == identity]
        if len(matching) > 1:
            raise ValueError("Catalog function has multiple persisted C++ source bindings")
        for unit in units:
            if unit.get("kind") != "cpp" or unit.get("function_id") == identity:
                continue
            if unit.get("symbol") == symbol:
                raise ValueError("Authored C++ symbol conflicts with another persisted catalog binding")
            if unit.get("source") == relative.as_posix():
                raise ValueError("Authored C++ source path conflicts with another persisted catalog binding")
        new_unit = {"function_id": identity, "kind": "cpp", "source": relative.as_posix(),
                    "symbol": symbol, "sha256": digest, "revision": digest, "language": language}
        if matching:
            matching[0].update(new_unit)
        else:
            units.append(new_unit)
        _atomic_json(self.units_path, document)

    def _remove_cpp_unit(self, identity):
        document = self._assembly_unit_state()
        units = document.get("units")
        if not isinstance(units, list):
            raise ValueError("Compiled workstation units have no valid unit list")
        document["units"] = [unit for unit in units
                             if not (unit.get("kind") == "cpp" and unit.get("function_id") == identity)]
        _atomic_json(self.units_path, document)

    def build_source_units(self, catalog_document=None):
        """Return baseline bindings plus saved catalog-function C++ revisions.

        The caller passes this in-memory document to the native alias resolver
        and source catalog; the explicit source-units.json is never rewritten.
        User-created helper functions have no native identity and are omitted.
        A build-owned catalog snapshot may be supplied to avoid consulting live
        SQLite names after the build has pinned its catalog inputs.
        """
        image = (self._catalog or self._load_catalog())["image_sha256"]
        if catalog_document is None:
            catalog_rows = self._rows()
        else:
            if (not isinstance(catalog_document, dict) or
                    catalog_document.get("image_sha256") != image):
                raise ValueError("Build-owned catalog belongs to another Replay image")
            functions = catalog_document.get("functions")
            symbols = catalog_document.get("symbols")
            if not isinstance(functions, list) or not isinstance(symbols, list):
                raise ValueError("Build-owned catalog has no valid function/symbol lists")
            if any(not isinstance(row, dict) for row in functions + symbols):
                raise ValueError("Build-owned catalog contains a malformed row")
            catalog_rows = [*functions, *symbols]
        baseline_units = self.root / "source-units.json"
        document = json.loads(baseline_units.read_text(encoding="utf-8")) if baseline_units.exists() else {
            "schema": 1, "image_sha256": image, "units": [], "imports": []}
        if document.get("schema") != 1 or document.get("image_sha256") not in (None, image):
            raise ValueError("source-units.json belongs to another Replay image or schema")
        units = document.get("units")
        if not isinstance(units, list):
            raise ValueError("source-units.json has no valid C++ unit list")
        seen_ids = set()
        seen_symbols = {}
        for unit in units:
            if not isinstance(unit, dict):
                raise ValueError("Explicit source-unit binding is malformed")
            identity, symbol = unit.get("function_id"), unit.get("symbol")
            if not isinstance(identity, str) or not isinstance(symbol, str):
                raise ValueError("Explicit source-unit binding is malformed")
            if identity in seen_ids:
                raise ValueError("Duplicate explicit source-unit function identity")
            if symbol in seen_symbols and seen_symbols[symbol] != identity:
                raise ValueError("One explicit C++ symbol is bound to multiple catalog functions")
            seen_ids.add(identity)
            seen_symbols[symbol] = identity
        rows_by_id = {row["id"]: row for row in catalog_rows
                      if row.get("kind", "function") == "function"}
        persisted = self._assembly_unit_state().get("units", [])
        persisted_ids = set()
        for unit in persisted:
            if unit.get("kind") != "cpp":
                continue
            identity, symbol = unit.get("function_id"), unit.get("symbol")
            if not isinstance(identity, str) or not isinstance(symbol, str):
                raise ValueError("Persisted catalog C++ binding is malformed")
            if identity in persisted_ids:
                raise ValueError("Duplicate persisted catalog C++ identity")
            persisted_ids.add(identity)
            row = rows_by_id.get(identity)
            if row is None:
                raise ValueError("Persisted C++ binding refers to an unknown catalog function")
            relative = Path(unit.get("source", ""))
            digest = unit.get("sha256")
            if unit.get("revision") != digest or not digest:
                raise ValueError("Persisted catalog C++ source revision metadata is malformed")
            if relative.is_absolute() or ".." in relative.parts or relative.suffix not in (".cpp", ".c"):
                raise ValueError("Persisted catalog C++ source path is invalid")
            owners = [candidate for candidate in catalog_rows
                      if symbol == candidate["id"] or symbol == candidate.get("name") or
                      symbol in candidate.get("aliases", [])]
            if any(candidate["id"] != identity for candidate in owners):
                raise ValueError("Persisted C++ symbol is claimed by another catalog function")
            source = (self.root / relative).resolve()
            if not source.is_relative_to(self.root / "src") or not source.is_file():
                raise ValueError("Saved catalog C++ source is missing or outside src/")
            if sha256(source.read_bytes()) != digest:
                raise ValueError("Saved catalog C++ source revision/hash mismatch")
            if identity in seen_ids:
                existing = next(item for item in units if item.get("function_id") == identity)
                if existing.get("symbol") != symbol or Path(existing.get("source", "")) != relative:
                    raise ValueError("Persisted C++ binding conflicts with the explicit source-unit binding")
                continue
            if symbol in seen_symbols and seen_symbols[symbol] != identity:
                raise ValueError("Authored C++ symbol conflicts with another catalog function")
            units.append({"source": relative.as_posix(), "symbol": symbol, "function_id": identity})
            seen_ids.add(identity)
            seen_symbols[symbol] = identity
        document["units"] = units
        return document

    def list_sources(self, query="", offset=0, limit=100, kind=None):
        if offset < 0 or limit < 1 or limit > 1000:
            raise ValueError("offset must be nonnegative and limit must be 1..1000")
        result, total = self.list_source_rows(query, kind)
        return result[offset:offset + limit], total

    def list_source_rows(self, query="", kind=None):
        """Build the complete filtered source inventory once for tree consumers.

        `list_sources` remains the paginated API. Callers that need to build a
        virtual hierarchy should use this method instead of repeatedly asking
        for pages, because each page requires the same catalog/state joins.
        """
        catalog = self._catalog or self._load_catalog()
        rows = self._rows()
        function_ids = {r["id"] for r in catalog["functions"]}
        if kind in ("function", "functions"):
            rows = [r for r in rows if r.get("kind", "function") == "function"]
        elif kind in ("symbol", "symbols"):
            # Catalog functions may omit kind; both partitions use the same default.
            rows = [r for r in rows if r.get("kind", "function") != "function"]
        elif kind not in (None, "all"):
            raise ValueError("kind must be function, symbol, or all")
        query_fold = query.casefold()
        state = self._state()
        explicit_cpp_ids = {unit.get("function_id") for unit in self._bound_cpp_units()}
        persisted_units = self._assembly_unit_state().get("units", [])
        if not isinstance(persisted_units, list):
            raise ValueError("Compiled workstation units have no valid unit list")
        persisted_cpp_ids = {unit.get("function_id") for unit in persisted_units
                             if isinstance(unit, dict) and unit.get("kind") == "cpp"}
        persisted_assembly_ids = {unit.get("function_id") for unit in persisted_units
                                  if isinstance(unit, dict) and unit.get("kind") == "assembly"}
        result = []
        for row in rows:
            editable = state["sources"].get(row["id"], {})
            display_name = self._display_name(row)
            haystack = " ".join([row["id"], display_name, row.get("name", ""), *row.get("aliases", [])]).casefold()
            if query_fold and query_fold not in haystack:
                continue
            result.append({"id": row["id"], "name": display_name, "rva": row["rva"],
                           "kind": row.get("kind", "function"), "aliases": row.get("aliases", []),
                           "variants": ["cpp"],
                           "has_cpp": bool(editable.get("cpp")) or row["id"] in explicit_cpp_ids or
                                     row["id"] in persisted_cpp_ids,
                           "has_assembly_edit": bool(editable.get("assembly")) or
                                                row["id"] in persisted_assembly_ids,
                           "revision": None})
        if kind in (None, "all", "function", "functions", "user-function"):
            for identity, user in state.get("user_sources", {}).items():
                haystack = f"{identity} {user['name']}".casefold()
                if not query_fold or query_fold in haystack:
                    result.append({"id": identity, "name": user["name"], "rva": None, "kind": "user-function",
                                   "aliases": [], "variants": ["cpp"], "has_cpp": True,
                                   "has_assembly_edit": False, "revision": user["revision"]})
        return result, len(result)

    def get_source(self, identity, variant="assembly"):
        if variant == "c":
            variant = "cpp"
        if variant not in ("assembly", "cpp", "pseudocode"):
            raise ValueError("variant must be assembly, cpp, or pseudocode")
        try:
            row = self._by_identity(identity)
        except KeyError:
            user = self._state().get("user_sources", {}).get(identity)
            if not user:
                raise
            if variant != "cpp":
                raise ValueError("User-authored additions have C++ source only")
            path = (self.root / user["path"]).resolve()
            if not path.is_relative_to(self.root / "src") or not path.is_file():
                raise ValueError("Managed user C++ source is missing or outside src/")
            content = path.read_bytes().decode("utf-8")
            if sha256(content.encode()) != user["sha256"]:
                raise ValueError("Managed user source changed outside revision API")
            return {"id": identity, "name": user["name"], "variant": "cpp", "language": user.get('language', 'cpp'),
                    "content": content, "revision": user["revision"], "editable": True, "compilable": True,
                    "symbol": user['name'], "source": user['path'],
                    "provenance": user["provenance"]}
        if row.get("kind", "function") != "function" and variant == "cpp":
            content = f"/* Native symbol {row['id']}; its complete C type and extent are not recovered. */\nextern unsigned char {row['id']}[];\n"
            return {'id': row['id'], 'name': self._display_name(row), 'variant': 'cpp', 'language': 'cpp',
                    'content': content, 'revision': sha256(content.encode()), 'editable': False, 'compilable': False,
                    'provenance': {'basis': 'Catalog symbol declaration', 'abi_confidence': 'unknown extent and type'}}
        if row.get("kind", "function") != "function" and variant != "assembly":
            raise ValueError("Only function entries have C++ or pseudocode variants")
        catalog = self._catalog or self._load_catalog()
        state = self._state()["sources"].get(row["id"], {})
        current = state.get(variant)
        if current:
            path = self.root / current["path"]
            content = path.read_bytes().decode("utf-8")
            if sha256(content.encode()) != current["sha256"]:
                raise ValueError(f"Workstation source changed outside revision API: {path}")
            return {"id": row["id"], "name": self._display_name(row), "variant": variant, "language": current["language"],
                    "content": content, "revision": current["revision"],
                    **({"symbol": current.get("symbol"), "source": current["path"]} if variant == "cpp" else {}),
                    "editable": True,
                    "compilable": current["compilable"], "provenance": current["provenance"]}
        if variant == "cpp":
            units = self._bound_cpp_units()
            symbol, relative = self._cpp_mapping(row)
            unit = next((u for u in units if u["function_id"] == row["id"]), None)
            if unit:
                path = (self.root / unit["source"]).resolve()
                if not path.is_relative_to(self.root / "src") or not path.is_file():
                    raise ValueError("Existing C++ association escapes src/ or is missing")
                content = path.read_text(encoding="utf-8")
                return {"id": row["id"], "name": self._display_name(row), "variant": "cpp", "language": "cpp", "content": content,
                        "revision": sha256(content.encode()), "editable": True, "compilable": True,
                        "symbol": unit["symbol"], "source": path.relative_to(self.root).as_posix(),
                        "provenance": {"basis": "existing source-units.json association", "source": path.relative_to(self.root).as_posix(),
                                       "symbol": unit["symbol"], "abi_confidence": "unverified; authored declaration is not inferred"}}
            persisted = self._persisted_cpp_binding(row["id"])
            if persisted:
                relative = persisted["relative"].as_posix()
                return {"id": row["id"], "name": self._display_name(row), "variant": "cpp", "language": persisted['unit'].get('language', 'cpp'),
                        "content": persisted["content"], "revision": persisted["revision"],
                        "editable": True, "compilable": True,
                        "symbol": persisted["unit"]["symbol"], "source": relative,
                        "provenance": {"basis": "persisted source-workstation C++ association",
                                       "source": relative, "symbol": persisted["unit"]["symbol"],
                                       "abi_confidence": "unverified; authored declaration is not inferred"}}
            if self._state().get("user_sources", {}).get(row["id"]):
                raise ValueError("Catalog function identity conflicts with a user-source identity")
            return self.cpp_index().get(row)
        if variant == "pseudocode":
            texts = self._entry_text().get(f"{row['rva']:x}", {})
            content = texts.get("ida_pseudocode_override") or texts.get("clean_pseudo") or texts.get("pseudocode") or ""
            basis = "IDA function-text override" if texts.get("ida_pseudocode_override") else "Replay SQLite IDA pseudocode" if content else "no pseudocode row"
            return {"id": row["id"], "name": self._display_name(row), "variant": "pseudocode", "language": "ida-pseudocode",
                    "content": content, "revision": sha256(content.encode()) if content else None,
                    "editable": False, "compilable": False,
                    "provenance": {"basis": basis, "database_image_sha256": catalog["image_sha256"],
                                   "note": "Decompiler output is informational, not source C++ or compiler input."}}
        return self._assembly_source(row)

    def _assembly_source(self, row):
        rva = row["rva"]
        current = self._state()["sources"].get(row["id"], {}).get("assembly")
        if current:
            path = self.root / current["path"]
            content = path.read_text(encoding="utf-8")
            if sha256(content.encode()) != current["sha256"]:
                raise ValueError("Assembly source changed outside revision API")
            return {"id": row["id"], "name": self._display_name(row), "variant": "assembly", "language": "x86_64-coff-asm",
                    "content": content, "revision": current["revision"], "editable": True,
                    "compilable": True, "provenance": current["provenance"]}
        persisted = self._persisted_assembly_binding(row["id"])
        if persisted:
            relative = persisted["relative"].as_posix()
            return {"id": row["id"], "name": self._display_name(row), "variant": "assembly",
                    "language": "x86_64-coff-asm", "content": persisted["content"],
                    "revision": persisted["revision"], "editable": True, "compilable": True,
                    "source": relative,
                    "provenance": {"basis": "persisted source-workstation assembly association",
                                   "source": relative, "function_id": row["id"]}}
        generated = self.root / "generated"
        manifest = json.loads((generated / "manifest.json").read_text())
        section = manifest["sections"][0]
        entry_spans = self._function_spans(rva, manifest)
        if not entry_spans:
            return {"id": row["id"], "name": self._display_name(row), "variant": "assembly", "language": "x86_64-coff-asm",
                    "content": "", "revision": None, "editable": False, "compilable": False,
                    "provenance": {"basis": "PE ownership/CFG did not prove a complete function range"}}
        self._active_spans = entry_spans
        try:
            instructions = self._instruction_map(manifest)
        finally:
            del self._active_spans
        boundaries = set()
        for start, end in entry_spans:
            boundaries.update(a for a, _ in instructions.items() if start <= a < end)
        if rva not in boundaries:
            raise ValueError("Proven function entry has no compiler assembly instructions")
        unwind_error = None
        try:
            seh, unwind_meta = self._seh_directives(rva, entry_spans, instructions)
        except ValueError as error:
            seh, unwind_meta = {"required": False, "after": {}, "prologue_end": 0}, {"required": True, "supported": False}
            unwind_error = str(error)
        labels = set(seh.get("code_labels", []))
        # Stable per-instruction labels let the linker migrate recovered
        # absolute/RIP references into replaced function interiors exactly.
        labels.update(address for address in instructions
                      if self._instruction_size(address) not in (0, 255) and
                      any(start <= address < end for start, end in entry_spans))
        for address, line in instructions.items():
            for ref in re.findall(r"\breplay_rva_([0-9a-f]{8})\b", line):
                target = int(ref, 16)
                if (target in instructions and self._instruction_size(target) not in (0, 255) and
                        any(a <= target < b for a, b in entry_spans)):
                    labels.add(target)
            for ref in re.findall(r"\bimage\s*\+\s*0x([0-9a-fA-F]+)\b", line):
                target = int(ref, 16)
                if (target in instructions and self._instruction_size(target) not in (0, 255) and
                        any(a <= target < b for a, b in entry_spans)):
                    labels.add(target)
        rendered = [".intel_syntax noprefix", ".text", f".globl {row['id']}"]
        if seh["required"]:
            rendered.append(f".seh_proc {row['id']}")
        rendered.append(f"{row['id']}:")
        ended_prologue = False
        if seh["required"] and seh["prologue_end"] <= rva:
            rendered.append(".seh_endprologue")
            ended_prologue = True
        for start, end in entry_spans:
            for address in sorted(a for a in instructions if start <= a < end):
                if address in labels and address != rva:
                    rendered.append(f"L_{address:08x}:")
                line = instructions[address]
                line = re.sub(r"\{disp(?:8|32)\}\s*", "", line)
                def resolve_target(target):
                    if target == rva:
                        return row["id"]
                    if (target in instructions and self._instruction_size(target) not in (0, 255) and
                            any(a <= target < b for a, b in entry_spans)):
                        return f"L_{target:08x}"
                    return self._catalog_symbol(target)
                for ref in re.findall(r"\breplay_rva_([0-9a-f]{8})\b", line):
                    target = int(ref, 16)
                    line = re.sub(rf"\breplay_rva_{ref}\b", resolve_target(target), line)
                for ref in re.findall(r"\bimage\s*\+\s*0x([0-9a-fA-F]+)\b", line):
                    target = int(ref, 16)
                    line = re.sub(rf"\bimage\s*\+\s*0x{ref}\b", resolve_target(target), line,
                                  flags=re.IGNORECASE)
                rendered.append(line)
                after = address + self._instruction_size(address)
                rendered.extend(seh["after"].get(after, []))
                if seh["required"] and not ended_prologue and after >= seh["prologue_end"]:
                    rendered.append(".seh_endprologue")
                    ended_prologue = True
            if end in labels and end not in instructions:
                rendered.append(f"L_{end:08x}:")
        if seh["required"]:
            if not ended_prologue:
                rendered.append(".seh_endprologue")
            rendered.extend(seh.get("handler_lines", []))
            rendered.append(".seh_endproc")
        content = "\n".join(rendered) + "\n"
        editable = unwind_error is None and (len(entry_spans) == 1 or bool(unwind_meta.get("chain_folded")))
        return {"id": row["id"], "name": self._display_name(row), "variant": "assembly", "language": "x86_64-coff-asm",
                "content": content, "revision": sha256(content.encode()), "editable": editable, "compilable": editable,
                "provenance": {"basis": "recovered compiler assembly, bounded by PE unwind ownership or proven leaf CFG",
                               "image_sha256": manifest["input_sha256"], "ranges": entry_spans,
                               "rva": rva, "source_kind": "compiler assembly, not IDA disassembly",
                               "unwind": unwind_meta,
                               "editability_limit": unwind_error if unwind_error else (None if editable else "The compiler/backend currently requires one contiguous function range for an assembly replacement.")}}

    def _instruction_size(self, address):
        return self._native_index.lengths[address - self._native_index.text]

    def _seh_directives(self, rva, spans, instructions):
        """Recreate common Win64 unwind directives from the pinned PE record.

        Handler/chained records and unknown unwind opcodes remain view-only;
        their details are never guessed into COFF metadata.
        """
        rows = [row for row in self._native_index.rows if row[0] == rva]
        if not rows:
            return {"required": True, "after": {}, "prologue_end": rva}, {"required": True, "original_unwind": False}
        if len(rows) != 1:
            raise ValueError("Assembly editing requires one primary PE runtime-function record")
        begin, _, unwind = rows[0]
        def read_data(at, size):
            for section, block in self._native_sources:
                offset = at-section["rva"]
                if 0 <= offset and offset+size <= len(block):
                    return block[offset:offset+size]
            raise ValueError(f"Unwind metadata outside initialized source at {at:#x}")
        header = read_data(unwind, 4)
        version, flags, prologue_size, count, frame = header[0] & 7, header[0] >> 3, header[1], header[2], header[3]
        meta = {"required": True, "unwind_rva": unwind, "version": version, "flags": flags,
                "prologue_size": prologue_size, "code_slots": count, "frame": frame}
        if version not in (1, 2):
            raise ValueError("Assembly editing cannot regenerate an unknown unwind version")
        family_rows = [row for row in self._native_index.rows if self._native_index.parents[row] == rva]
        family_flags = {}
        for family_row in family_rows:
            family_header = read_data(family_row[2], 4)
            family_flags[family_row[0]] = family_header[0] >> 3
        if flags & 4:
            raise ValueError("The primary runtime-function record carries chained unwind data")
        handler_lines = []
        scope_labels = set()
        if flags & 3:
            extra = unwind + 4 + ((count + 1) & ~1) * 2
            handler_rva = struct.unpack("<I", read_data(extra, 4))[0]
            handler_id = self._catalog_symbol(handler_rva)
            range_ends = {end for _start, end in spans}

            def code_label(address, *, allow_end=False):
                if address == 0:
                    return None
                if address == rva:
                    return row["id"]
                if any(start <= address < end for start, end in spans):
                    if (address not in instructions or
                            self._instruction_size(address) in (0, 255)):
                        raise ValueError(f"Scope address {address:#x} is not a recovered instruction boundary")
                    return f"L_{address:08x}"
                if allow_end and address in range_ends:
                    return f"L_{address:08x}"
                return None

            from workstation_seh import (RvaField, ScopeRecord, render_cpp_funcinfo_handler,
                                         render_rva_fields, render_scope_handler)
            if handler_rva in {0x21cd220, 0x21f7874}:
                if flags not in (1, 3):
                    raise ValueError("C-specific scope tables require EHANDLER flags")
                scope_count = struct.unpack("<I", read_data(extra + 4, 4))[0]
                if scope_count > 100000:
                    raise ValueError("Invalid C-specific scope count")
                scope_bytes = read_data(extra + 8, scope_count * 16)
                source_records = [struct.unpack_from("<IIII", scope_bytes, index * 16)
                                  for index in range(scope_count)]
                decoded_scopes = []
                for scope_begin, scope_end, scope_handler, jump_target in source_records:
                    begin_label = code_label(scope_begin)
                    end_label = code_label(scope_end, allow_end=True)
                    if begin_label is None or end_label is None:
                        raise ValueError("C-specific scope bounds fall outside the recovered owner function")
                    if scope_handler:
                        handler_label = code_label(scope_handler)
                        if handler_label is None:
                            handler_label = self._catalog_symbol(scope_handler)
                    else:
                        handler_label = None
                    jump_label = code_label(jump_target) if jump_target else None
                    if jump_target and jump_label is None:
                        jump_label = self._catalog_symbol(jump_target)
                    decoded_scopes.append(ScopeRecord(begin_label, end_label, handler_label, jump_label))
                    scope_labels.update(label for label in (begin_label, end_label, jump_label)
                                        if label and label.startswith("L_"))

                emitted_label_order = []
                function_id = self._catalog_symbol(rva)
                if function_id in {record.begin for record in decoded_scopes} | {record.end for record in decoded_scopes}:
                    emitted_label_order.append(function_id)
                for start, end in spans:
                    for address in sorted(a for a in scope_labels if a.startswith("L_")
                                          and start <= int(a[2:], 16) < end):
                        if address not in emitted_label_order:
                            emitted_label_order.append(address)
                    end_label = f"L_{end:08x}"
                    if end_label in scope_labels and end_label not in emitted_label_order:
                        emitted_label_order.append(end_label)
                handler_lines = render_scope_handler(handler_id, decoded_scopes,
                                                     label_order=emitted_label_order,
                                                     flags=flags).splitlines()
                meta["handler"] = {"kind": "seh_scope_table", "handler_id": handler_id,
                                   "scope_count": scope_count, "flags": flags,
                                   "source_scope_rvas": [list(record) for record in source_records],
                                   "regenerated_as": "label-based ADDR32NB scope table"}
            elif handler_rva in {0x21cd92c, 0x21f77f4}:
                if flags not in (1, 2, 3):
                    raise ValueError("Invalid C++ exception-handler flags")
                funcinfo_rva = struct.unpack("<I", read_data(extra + 4, 4))[0]
                funcinfo_label, funcinfo_data = self._clone_funcinfo_graph(
                    rva, funcinfo_rva, spans, instructions, scope_labels,
                    read_data, RvaField)
                handler_lines = render_cpp_funcinfo_handler(handler_id, funcinfo_label,
                                                             flags=flags).splitlines()
                handler_lines.extend(funcinfo_data)
                meta["handler"] = {"kind": "cpp_funcinfo_graph", "handler_id": handler_id,
                                   "funcinfo_rva": funcinfo_rva, "flags": flags,
                                   "regenerated_as": "cloned typed FuncInfo graph with label-based code RVAs"}
            else:
                raise ValueError(f"Handler metadata at {unwind:#x} is not a decoded supported handler family")
        chained = [row for row in family_rows if row[0] != rva]
        if any(family_flags.get(row[0]) != 4 for row in chained):
            raise ValueError("A discontiguous function range is not a verified CHAININFO record")
        if any(family_flags.get(row[0], 0) & 3 for row in chained):
            raise ValueError("Chained ranges with exception-handler data cannot be folded safely")
        if chained:
            meta["chain_folded"] = True
            meta["chain_record_count"] = len(chained)
            meta["chain_ranges"] = [[row[0], row[1]] for row in chained]
            meta["chain_handling"] = "Recovered blocks are emitted contiguously under the verified primary unwind record."
        slots = read_data(unwind+4, count*2)
        after = {}
        regs = ("rax", "rcx", "rdx", "rbx", "rsp", "rbp", "rsi", "rdi", "r8", "r9", "r10", "r11", "r12", "r13", "r14", "r15")
        i = 0
        while i < count:
            code_offset = slots[i*2]
            opinfo, op = slots[i*2+1] >> 4, slots[i*2+1] & 15
            i += 1
            if op == 0:
                directive = f".seh_pushreg {regs[opinfo]}"
            elif op == 1:
                if opinfo == 0 and i < count:
                    amount = struct.unpack_from("<H", slots, i*2)[0]*8; i += 1
                elif opinfo == 1 and i+1 < count:
                    amount = struct.unpack_from("<I", slots, i*2)[0]; i += 2
                else:
                    raise ValueError("Invalid UWOP_ALLOC_LARGE record")
                directive = f".seh_stackalloc {amount}"
            elif op == 2:
                directive = f".seh_stackalloc {opinfo*8+8}"
            elif op == 3:
                frame_reg, frame_units = frame & 15, frame >> 4
                directive = f".seh_setframe {regs[frame_reg]}, {frame_units*16}"
            elif op in (4, 5):
                if op == 4 and i < count:
                    amount = struct.unpack_from("<H", slots, i*2)[0]*8; i += 1
                elif op == 5 and i+1 < count:
                    amount = struct.unpack_from("<I", slots, i*2)[0]; i += 2
                else:
                    raise ValueError("Invalid UWOP_SAVE_NONVOL record")
                directive = f".seh_savereg {regs[opinfo]}, {amount}"
            elif op in (8, 9):
                if op == 8 and i < count:
                    amount = struct.unpack_from("<H", slots, i*2)[0]*16; i += 1
                elif op == 9 and i+1 < count:
                    amount = struct.unpack_from("<I", slots, i*2)[0]; i += 2
                else:
                    raise ValueError("Invalid UWOP_SAVE_XMM128 record")
                directive = f".seh_savexmm128 xmm{opinfo}, {amount}"
            elif op == 10 and opinfo in (0, 1):
                directive = f".seh_pushframe {opinfo}"
            else:
                raise ValueError(f"Unsupported Win64 unwind opcode {op}; function is view-only")
            after.setdefault(begin+code_offset, []).append(directive)
        if frame >> 4 and not any(d.startswith(".seh_setframe") for ds in after.values() for d in ds):
            raise ValueError("Frame register is set but no UWOP_SET_FPREG describes it")
        valid_ends = {at+self._instruction_size(at) for at in instructions}
        if any(at not in valid_ends for at in after):
            raise ValueError("An unwind code offset does not align with a recovered prologue instruction")
        return {"required": True, "after": after, "prologue_end": begin+prologue_size,
                "handler_lines": handler_lines,
                "code_labels": sorted(int(label[2:], 16) for label in scope_labels)}, meta

    def _clone_funcinfo_graph(self, owner_rva, funcinfo_rva, spans, instructions, code_labels,
                              read_data, RvaField):
        """Clone the typed MSVC EH graph and translate code RVAs to labels."""
        emitted = []
        node_labels = {}

        def node_label(kind, address):
            key = (kind, address)
            if key not in node_labels:
                node_labels[key] = f"L_eh_{kind}_{address:08x}"
            return node_labels[key]

        def store_node(kind, address, words):
            key = (kind, address)
            label = node_label(kind, address)
            if key not in {entry[0] for entry in emitted}:
                emitted.append((key, label, words))
            return label

        def data_ref(address):
            return 0 if address == 0 else RvaField(self._catalog_symbol(address))

        def code_ref(address):
            if address == 0:
                return 0
            if address == owner_rva:
                return RvaField(self._catalog_symbol(address))
            for start, end in spans:
                if start <= address < end:
                    if (address not in instructions or
                            self._instruction_size(address) in (0, 255)):
                        raise ValueError(f"C++ EH code RVA {address:#x} is not a recovered instruction boundary")
                    label = f"L_{address:08x}"
                    code_labels.add(label)
                    return RvaField(label)
                if address == end:
                    label = f"L_{address:08x}"
                    code_labels.add(label)
                    return RvaField(label)
            return data_ref(address)

        def read_words(address, count):
            if count < 0 or count > 100000:
                raise ValueError("C++ EH metadata array count is outside the supported bound")
            data = read_data(address, count * 4)
            return list(struct.unpack(f"<{count}I", data)) if count else []

        def handler_array(address, count):
            if not address and count:
                raise ValueError("C++ EH handler array has a null RVA")
            if count > 10000:
                raise ValueError("Invalid C++ handler count")
            raw = read_words(address, count * 5)
            for index in range(count):
                base = index * 5
                raw[base + 1] = data_ref(raw[base + 1])
                raw[base + 3] = code_ref(raw[base + 3])
            return store_node("handlers", address, raw)

        signature, states, unwind_map, tries, try_map, ip_count, ip_map, unwind_help, es_list, eh_flags = struct.unpack(
            "<10I", read_data(funcinfo_rva, 40))
        if signature & 0x1fffffff not in (0x19930520, 0x19930521, 0x19930522):
            raise ValueError(f"Unsupported C++ FuncInfo format at {funcinfo_rva:#x}")
        if max(states, tries, ip_count) > 10000:
            raise ValueError("C++ FuncInfo map count exceeds the supported bound")

        unwind_label = 0
        if states:
            if not unwind_map:
                raise ValueError("C++ FuncInfo unwind map has a null RVA")
            raw = read_words(unwind_map, states * 2)
            for index in range(states):
                raw[index * 2 + 1] = code_ref(raw[index * 2 + 1])
            unwind_label = RvaField(store_node("unwind", unwind_map, raw))

        try_label = 0
        if tries:
            if not try_map:
                raise ValueError("C++ FuncInfo try map has a null RVA")
            raw = read_words(try_map, tries * 5)
            for index in range(tries):
                base = index * 5
                handler_count, handler_at = raw[base + 3], raw[base + 4]
                if handler_count:
                    raw[base + 4] = RvaField(handler_array(handler_at, handler_count))
                elif handler_at:
                    raise ValueError("Empty C++ try block has a nonnull handler-array pointer")
            try_label = RvaField(store_node("try", try_map, raw))

        ip_label = 0
        if ip_count:
            if not ip_map:
                raise ValueError("C++ FuncInfo IP-state map has a null RVA")
            raw = read_words(ip_map, ip_count * 2)
            for index in range(ip_count):
                raw[index * 2] = code_ref(raw[index * 2])
            ip_label = RvaField(store_node("ip", ip_map, raw))

        es_label = 0
        if es_list:
            count, handlers = struct.unpack("<II", read_data(es_list, 8))
            if count > 10000 or (count and not handlers):
                raise ValueError("Invalid C++ exception-specification handler list")
            cloned_handlers = RvaField(handler_array(handlers, count)) if count else 0
            es_label = RvaField(store_node("es", es_list, [count, cloned_handlers]))

        root = [signature, states, unwind_label, tries, try_label, ip_count,
                ip_label, unwind_help, es_label, eh_flags]
        root_label = store_node("funcinfo", funcinfo_rva, root)
        from workstation_seh import render_rva_fields
        data_lines = ['.section .rdata,"dr"']
        for _key, label, words in emitted:
            data_lines.append(label + ":")
            data_lines.extend(render_rva_fields(words))
        data_lines.append(".text")
        return root_label, data_lines

    def _function_spans(self, rva, manifest):
        # Recreate the same PE ownership/CFG index as the linker. For a named
        # unwind family use every owned range; otherwise require a complete
        # bounded leaf CFG derived from direct references in compiler source.
        import native_functions
        if self._native_index is None:
            sources = [(s, (self.root / "generated" / s["file"]).read_bytes()) for s in manifest["sections"] if "file" in s]
            def read_data(at, size):
                for section, data in sources:
                    offset = at-section["rva"]
                    if 0 <= offset and offset+size <= len(data):
                        return data[offset:offset+size]
                raise ValueError(f"Native metadata outside initialized source at {at:#x}")
            catalog = self._catalog or self._load_catalog()
            manifest["function_entries"] = sorted({r["rva"] for r in catalog["functions"]})
            self._native_index = native_functions.FunctionIndex(manifest, read_data, (self.root / "generated" / "instruction-lengths.bin").read_bytes())
            self._native_sources = sources
        index = self._native_index
        def read_data(at, size):
            for section, data in self._native_sources:
                offset = at-section["rva"]
                if 0 <= offset and offset+size <= len(data):
                    return data[offset:offset+size]
            raise ValueError(f"Native metadata outside initialized source at {at:#x}")
        if index.owner(rva) not in (None, rva):
            return []
        spans = index.families.get(rva)
        if spans:
            return [list(s) for s in sorted(spans)]
        try:
            self._active_spans = None
            instructions = self._instruction_map(manifest)
            lengths = index.lengths
            short = {int(a): int(b) for a, b in manifest.get("short_references", [])}
            todo, decoded = [rva], set()
            while todo:
                at = todo.pop()
                if at in decoded:
                    continue
                if at != rva and (at in index.entries or index.owner(at) is not None):
                    continue
                offset = at-index.text
                if (offset < 0 or offset >= len(lengths) or lengths[offset] in (0, 255) or at not in instructions
                        or abs(at-rva) > 0x100000 or len(decoded) >= 100000):
                    return []
                decoded.add(at)
                line = instructions[at]
                mnemonic = line.split(None, 1)[0].lower()
                if mnemonic in ("ret", "retf", "iretq", "ud2", "int3"):
                    continue
                if mnemonic.startswith(("j", "loop")):
                    refs = re.findall(r"\breplay_rva_([0-9a-f]{8})\b", line)
                    target = int(refs[-1], 16) if refs else short.get(at)
                    if target is None:
                        if mnemonic == "jmp" and "[rip" in line:
                            continue
                        return []
                    if target < rva and target not in index.entries and index.owner(target) is None:
                        return []
                    todo.append(target)
                    if mnemonic == "jmp":
                        continue
                todo.append(at+lengths[offset])
            spans = []
            for address in sorted(decoded):
                size = lengths[address-index.text]
                if spans and spans[-1][1] == address:
                    spans[-1][1] = address+size
                else:
                    spans.append([address, address+size])
            return spans
        except (ValueError, OSError, IndexError, KeyError):
            return []

    def _instruction_map(self, manifest):
        if self._instruction_cache is not None and not getattr(self, "_active_spans", None):
            return self._instruction_cache
        result = {}
        lengths = (self.root / "generated" / "instruction-lengths.bin").read_bytes()
        active_spans = getattr(self, "_active_spans", None)
        for chunk in manifest["chunks"]:
            chunk_start = chunk["rva"]
            chunk_end = chunk_start + chunk["size"]
            if active_spans and not any(a < chunk_end and b > chunk_start for a, b in active_spans):
                continue
            source = self.root / "generated" / "asm" / chunk["file"]
            current = None
            for line in source.read_text(encoding="utf-8").splitlines():
                match = re.fullmatch(r"\.org\s+0x([0-9a-fA-F]+),\s*0x[0-9a-fA-F]+", line.strip())
                if match:
                    current = chunk["rva"] + int(match[1], 16)
                    continue
                if current is not None and line and not line.startswith(".") and not line.endswith(":"):
                    instruction = re.sub(r"^\{disp(?:8|32)\}\s*", "", line.strip())
                    result[current] = instruction
                # Instruction sizes are taken from the generated per-byte table.
                if current is not None and current in result:
                    size = lengths[current-manifest["sections"][0]["rva"]]
                    if size not in (0, 255):
                        current += size
        if not active_spans:
            self._instruction_cache = result
        return result

    def save_source(self, identity, content, revision, variant="cpp", language=None):
        from workstation.build_lock import compiler_lock
        with compiler_lock(self.root / '.workstation-compiler.lock'):
            return self._save_source_unlocked(identity, content, revision, variant, language)

    def checkout_external(self, identity):
        """Record an immutable edit base before a native file is opened in VS Code."""
        import uuid
        from workstation.build_lock import compiler_lock
        with compiler_lock(self.root / '.workstation-compiler.lock'):
            baseline = self.get_source(identity, 'cpp')
            if not baseline.get('source'):
                raise ValueError('Promote the recovered candidate before checking out an authored source')
            path = (self.root / baseline['source']).resolve()
            if not path.is_relative_to(self.root / 'src'):
                raise ValueError('External editing is limited to authored files under src/')
            ticket = self.root / 'analysis' / 'cpp-recovery' / 'edits' / (uuid.uuid4().hex + '.json')
            metadata = [self.units_path, self.manifest_path, self.user_functions_path, self.root / 'source-units.json']
            record = {'schema': 1, 'image_sha256': (self._catalog or self._load_catalog())['image_sha256'],
                      'identity': baseline['id'], 'source': baseline['source'], 'symbol': baseline['symbol'],
                      'language': baseline.get('language', 'cpp'), 'revision': baseline['revision'],
                      'base_content': baseline['content'], 'consumed': False,
                      'base_raw_hex': path.read_bytes().hex(),
                      'metadata': [{'path': str(p), 'sha256': sha256(p.read_bytes()) if p.exists() else None} for p in metadata]}
            _atomic_json(ticket, record)
            return {'ticket': str(ticket), 'source': str(path), 'revision': baseline['revision'], 'symbol': baseline['symbol']}

    def reconcile_external(self, ticket_path):
        """Validate external edits and advance matching revision records together.

        Neither source version is overwritten. A conflicting metadata snapshot
        requires a fresh checkout after the versions have been reconciled.
        """
        from workstation.build_lock import compiler_lock
        from workstation_cpp_sources import compile_check
        ticket_path = Path(ticket_path).resolve()
        if not ticket_path.is_relative_to(self.root / 'analysis' / 'cpp-recovery' / 'edits'):
            raise ValueError('Select an edit ticket issued by this project')
        with compiler_lock(self.root / '.workstation-compiler.lock'):
            ticket = json.loads(ticket_path.read_text(encoding='utf-8'))
            image = (self._catalog or self._load_catalog())['image_sha256']
            if ticket.get('schema') != 1 or ticket.get('image_sha256') != image or ticket.get('consumed'):
                raise ValueError('Stale, consumed or foreign edit ticket')
            if sha256(ticket['base_content'].encode()) != ticket['revision']:
                raise ValueError('Edit ticket base does not match its revision')
            path = (self.root / ticket['source']).resolve()
            if not path.is_relative_to(self.root / 'src') or not path.is_file():
                raise ValueError('External source escapes src/ or is missing')
            expected_paths = {str(p): p for p in (self.units_path, self.manifest_path, self.user_functions_path, self.root / 'source-units.json')}
            if {item['path'] for item in ticket['metadata']} != set(expected_paths):
                raise ValueError('Edit ticket metadata set is invalid')
            def verify_metadata():
                for item in ticket['metadata']:
                    p = expected_paths[item['path']]
                    if (sha256(p.read_bytes()) if p.exists() else None) != item['sha256']:
                        raise ValueError('Revision conflict; metadata changed after checkout. Both source versions are preserved.')
            verify_metadata()
            raw = path.read_bytes()
            content = raw.decode('utf-8')
            digest = sha256(content.encode())
            checked = compile_check(self.root, content, ticket['symbol'], ticket['language'], source_path=path)
            if not checked['compiled']:
                raise ValueError('External source did not compile; no metadata changed.\n' + checked['diagnostics'])
            verify_metadata()
            if path.read_bytes() != raw:
                raise ValueError('External source changed during validation; retry')
            changes = {}
            for key, p in expected_paths.items():
                if not p.exists() or p == self.root / 'source-units.json':
                    continue
                data = json.loads(p.read_text(encoding='utf-8'))
                changed = False
                if p == self.units_path:
                    for unit in data.get('units', []):
                        if unit.get('kind') == 'cpp' and unit.get('function_id') == ticket['identity']:
                            if unit['revision'] != ticket['revision'] or unit['source'] != ticket['source']:
                                raise ValueError('Compiled source revision conflicts with edit base')
                            unit.update(sha256=digest, revision=digest)
                            changed = True
                elif p == self.manifest_path:
                    prior = data.get('sources', {}).get(ticket['identity'], {}).get('cpp')
                    user = data.get('user_sources', {}).get(ticket['identity'])
                    for entry in (prior, user):
                        if entry:
                            if entry['revision'] != ticket['revision']:
                                raise ValueError('Cached source revision conflicts with edit base')
                            entry.update(sha256=digest, revision=digest)
                            changed = True
                elif p == self.user_functions_path:
                    entry = data.get('functions', {}).get(ticket['identity'])
                    if entry:
                        if entry['revision'] != ticket['revision']:
                            raise ValueError('User source revision conflicts with edit base')
                        entry.update(sha256=digest, revision=digest)
                        changed = True
                if changed:
                    changes[p] = data
            history = self.cache_root / 'history' / ticket['identity'] / 'cpp' / (ticket['revision'] + '.txt')
            history.parent.mkdir(parents=True, exist_ok=True)
            if not history.exists():
                history.write_bytes(bytes.fromhex(ticket.get('base_raw_hex', ticket['base_content'].encode().hex())))
            revision_path = self.cache_root / 'revisions' / ticket['identity'] / 'cpp' / (digest + '.txt')
            revision_path.parent.mkdir(parents=True, exist_ok=True)
            revision_path.write_text(content, encoding='utf-8', newline='\n')
            before = {p: p.read_bytes() for p in changes}
            try:
                for p, data in changes.items():
                    _atomic_json(p, data)
                ticket.update(consumed=True, new_revision=digest, validation=checked)
                _atomic_json(ticket_path, ticket)
            except Exception:
                for p, previous in before.items():
                    p.write_bytes(previous)
                raise
            return {'source': str(path), 'revision': digest, 'compiled': True,
                    'behavior': 'intentional edit; baseline differential evidence must be updated separately',
                    'metadata_updated': list(map(str, changes))}

    def _save_source_unlocked(self, identity, content, revision, variant="cpp", language=None):
        if variant == "c":
            variant = "cpp"
        if variant not in ("cpp", "assembly", "pseudocode"):
            raise ValueError("variant must be cpp, assembly, or pseudocode")
        state = self._state()
        user = state.get("user_sources", {}).get(identity)
        if user:
            if variant != "cpp" or revision != user["revision"]:
                raise ValueError("Revision conflict or invalid variant")
            if not isinstance(content, str) or not content.strip():
                raise ValueError("Source content must be nonempty text")
            if not re.search(rf"\b{re.escape(user['name'])}\s*\(", content):
                raise ValueError(f"C++ source must keep defining {user['name']}")
            from workstation_cpp_sources import compile_check
            checked = compile_check(self.root, content, user['name'], user.get('language', 'cpp'))
            if not checked['compiled']:
                raise ValueError('Source did not compile; no revision was saved.\n' + checked['diagnostics'])
            digest = sha256(content.encode("utf-8"))
            if digest == revision:
                return self.get_source(identity, "cpp")
            path = (self.root / user["path"]).resolve()
            if not path.is_relative_to(self.root / "src") or not path.is_file() or sha256(path.read_bytes()) != revision:
                raise ValueError("Managed user source changed outside revision API")
            revision_path = self.cache_root / "revisions" / identity / "cpp" / f"{digest}.txt"
            revision_path.parent.mkdir(parents=True, exist_ok=True)
            revision_path.write_text(content, encoding="utf-8", newline="\n")
            history = self.cache_root / "history" / identity / "cpp" / f"{revision}.txt"
            history.parent.mkdir(parents=True, exist_ok=True)
            if not history.exists():
                history.write_bytes(path.read_bytes())
            path.write_text(content, encoding="utf-8", newline="\n")
            user["revision"] = digest
            user["sha256"] = digest
            _atomic_json(self.manifest_path, state)
            users = self._user_functions()
            users["functions"][identity]["revision"] = digest
            users["functions"][identity]["sha256"] = digest
            _atomic_json(self.user_functions_path, users)
            return self.get_source(identity, "cpp")
        row = self._by_identity(identity, "function")
        if not isinstance(content, str) or not content.strip():
            raise ValueError("Source content must be nonempty text")
        if variant == "pseudocode":
            language, compilable = "ida-pseudocode", False
        elif variant == "assembly":
            language, compilable = "x86_64-coff-asm", True
            if (not content.lstrip().startswith(".intel_syntax") or
                    not re.search(rf"(?m)^\.globl\s+{re.escape(row['id'])}\s*$", content) or
                    not re.search(rf"(?m)^\.seh_proc\s+{re.escape(row['id'])}\s*$", content) or
                    not re.search(rf"(?m)^{re.escape(row['id'])}:\s*$", content) or
                    not re.search(r"(?m)^\.seh_endprologue\s*$", content) or
                    not re.search(r"(?m)^\.seh_endproc\s*$", content)):
                raise ValueError("Assembly must be compiler syntax and define the selected stable function ID at offset zero")
            baseline = self.get_source(row["id"], "assembly")
            if not baseline["editable"]:
                raise ValueError("The backend cannot prove a single replaceable function range for this identity")
            self._validate_assembly_candidate(row["id"], content)
        else:
            baseline = self.get_source(row["id"], "cpp")
            requested_language = str(language or '').casefold()
            language, compilable = ('cpp' if requested_language in ('cpp', 'c++') else
                                    'c' if requested_language == 'c' else baseline.get("language", "cpp")), True
            # Compiler acceptance is separate from ABI reconstruction. The
            # build still checks native ownership and resolves linked symbols;
            # it cannot establish an unknown calling contract from source alone.
            symbol, _relative = self._cpp_mapping(row)
            if baseline.get("symbol"):
                symbol = baseline["symbol"]
            has_explicit = any(u.get("function_id") == row["id"] for u in self._bound_cpp_units())
            has_persisted = any(u.get("kind") == "cpp" and u.get("function_id") == row["id"]
                                for u in self._assembly_unit_state().get("units", []))
            if (not has_explicit and not has_persisted and symbol != row["id"] and
                    re.search(rf"\b{re.escape(row['id'])}\s*\(", content)):
                symbol = row["id"]
            if not re.search(rf"\b{re.escape(symbol)}\s*\(", content):
                raise ValueError(f"C++ source must define the selected catalog symbol {symbol}")
            if language == "c" or not has_explicit:
                from workstation_cpp_sources import compile_check
                checked = compile_check(self.root, content, symbol, language)
                if not checked["compiled"]:
                    raise ValueError(f"{'C' if language == 'c' else 'C++'} source did not compile; no revision was saved.\n" + checked["diagnostics"])
        old = state["sources"].get(row["id"], {}).get(variant)
        current_revision = old["revision"] if old else None
        if old is None:
            baseline = self.get_source(row["id"], variant)
            current_revision = baseline["revision"]
            if variant == "cpp" and current_revision and baseline["content"]:
                baseline_path = self.cache_root / "revisions" / row["id"] / "cpp" / f"{current_revision}.txt"
                baseline_path.parent.mkdir(parents=True, exist_ok=True)
                if not baseline_path.exists():
                    baseline_path.write_text(baseline["content"], encoding="utf-8", newline="\n")
        if revision != current_revision:
            raise ValueError("Revision conflict; reload the current source before saving")
        if old:
            prior_path = self.root / old['path']
            if prior_path.exists() and sha256(prior_path.read_bytes()) != old['sha256']:
                raise ValueError('Source has external edits; reconcile them before saving from the managed editor')
        digest = sha256(content.encode("utf-8"))
        new_revision = digest
        if old and old["sha256"] == digest:
            return self.get_source(row["id"], variant)
        revision_path = self.cache_root / "revisions" / row["id"] / variant / f"{digest}.txt"
        revision_path.parent.mkdir(parents=True, exist_ok=True)
        revision_path.write_text(content, encoding="utf-8", newline="\n")
        if old:
            prior_path = self.root / old["path"]
            if prior_path.exists():
                history = self.cache_root / "history" / row["id"] / variant / f"{old['revision']}.txt"
                history.parent.mkdir(parents=True, exist_ok=True)
                if not history.exists():
                    history.write_bytes(prior_path.read_bytes())
        if variant == "cpp":
            _mapped_symbol, relative = self._cpp_mapping(row)
            if language == "c" and old is None and not any(u.get("function_id") == row['id'] for u in self._bound_cpp_units()):
                relative = relative.with_suffix('.c')
            path = self.root / relative
            if not path.resolve().is_relative_to(self.root / "src"):
                raise ValueError("Bound C++ path escapes src/")
            if old is None and path.exists():
                existing_hash = sha256(path.read_text(encoding="utf-8").encode())
                if existing_hash != current_revision:
                    raise ValueError("Existing C++ source changed since it was opened")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            self._write_cpp_unit(row["id"], symbol, relative, digest, language)
        elif variant == "assembly":
            relative = Path("source-workstation") / "assembly" / f"{row['id']}.s"
            path = self.root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            units = self._assembly_unit_state()
            units["units"] = [u for u in units["units"] if not (u["function_id"] == row["id"] and u["kind"] == "assembly")]
            units["units"].append({"function_id": row["id"], "kind": "assembly", "source": relative.as_posix(),
                                   "sha256": digest, "revision": new_revision, "language": language})
            _atomic_json(self.units_path, units)
        else:
            relative = Path("source-workstation") / "pseudocode" / f"{row['id']}.txt"
            path = self.root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
        state["sources"].setdefault(row["id"], {})[variant] = {
            "path": relative.as_posix(), "language": language, "revision": new_revision, "sha256": digest,
            "compilable": compilable, "function_id": row["id"] if variant == "cpp" else None,
            "symbol": symbol if variant == "cpp" else None,
            "provenance": {"basis": "user-authored revision", "source_identity": row["id"],
                "target_catalog_image_sha256": state["image_sha256"], "target_rva_derived_by_catalog": row["rva"],
                "abi_confidence": "not inferred; compile/link and runtime validation remain distinct" if variant == "cpp" else "compiler-checked only"}}
        _atomic_json(self.manifest_path, state)
        return self.get_source(row["id"], variant)

    def create_source(self, name, language, content):
        variant = {"c": "cpp", "c++": "cpp", "cpp": "cpp", "assembly": "assembly", "asm": "assembly", "pseudocode": "pseudocode"}.get(language.casefold())
        if variant is None:
            raise ValueError("language must be C, C++, assembly, or pseudocode")
        try:
            row = self._by_identity(name, "function")
        except KeyError:
            if variant != "cpp" or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
                raise ValueError("A new source must be a named C++ function with a valid external symbol")
            state = self._state()
            identity = "user_" + hashlib.sha256(name.encode("utf-8")).hexdigest()[:16]
            if identity in state.get("user_sources", {}):
                if state["user_sources"][identity]["name"] != name:
                    raise ValueError("Stable user-source identity collision")
                return self.save_source(identity, content, state["user_sources"][identity]["revision"], "cpp", language)
            if not re.search(rf"\b{re.escape(name)}\s*\(", content):
                raise ValueError(f"New C++ source must define the selected user symbol {name}")
            digest = sha256(content.encode("utf-8"))
            native_language = 'c' if language.casefold() == 'c' else 'cpp'
            if native_language in ('c', 'cpp'):
                from workstation_cpp_sources import compile_check
                checked = compile_check(self.root, content, name, native_language)
                if not checked['compiled']:
                    raise ValueError(f"{'C' if native_language == 'c' else 'C++'} source did not compile; no function was created.\n" + checked['diagnostics'])
            relative = Path("src") / f"workstation_{identity}.{native_language}"
            path = self.root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            if path.exists():
                raise ValueError("Managed new-source path already exists")
            path.write_text(content, encoding="utf-8", newline="\n")
            revision_path = self.cache_root / "revisions" / identity / "cpp" / f"{digest}.txt"
            revision_path.parent.mkdir(parents=True, exist_ok=True)
            revision_path.write_text(content, encoding="utf-8", newline="\n")
            user = {"name": name, "path": relative.as_posix(), "revision": digest, "sha256": digest, "language": native_language,
                    "provenance": {"basis": "user-authored new C++ function", "target": "new linked symbol; no native function identity",
                                   "abi_confidence": "authored by user; no native prototype inferred"}}
            state.setdefault("user_sources", {})[identity] = user
            _atomic_json(self.manifest_path, state)
            users = self._user_functions()
            users["functions"][identity] = {"name": name, "path": relative.as_posix(), "revision": digest, "sha256": digest, 'language': native_language}
            _atomic_json(self.user_functions_path, users)
            return self.get_source(identity, "cpp")
        baseline = self.get_source(row["id"], variant)
        return self.save_source(row["id"], content, baseline["revision"], variant, language)

    def _validate_assembly_candidate(self, identity, content):
        """Run the project compiler before committing an assembly revision."""
        from coff import read
        from build import compile_one
        work = self.root / "source-workstation" / "validation"
        work.mkdir(parents=True, exist_ok=True)
        digest = sha256(content.encode("utf-8"))
        source = work / f"{identity}-{digest}.s"
        target = self.root / "build" / "workstation-validation" / f"{identity}-{digest}.obj"
        target.parent.mkdir(parents=True, exist_ok=True)
        source.write_text(content, encoding="utf-8", newline="\n")
        try:
            compile_one(source, target)
            proof = verify_assembly_coff(identity, read(target))
            return proof
        finally:
            for path in (source, target, target.with_suffix(".errors.txt")):
                if path.exists():
                    path.unlink()

    def remove_source(self, identity, revision, variant="cpp"):
        if variant not in ("cpp", "assembly", "pseudocode"):
            raise ValueError("variant must be cpp, assembly, or pseudocode")
        state = self._state()
        user = state.get("user_sources", {}).get(identity)
        if user:
            if variant != "cpp" or user["revision"] != revision:
                raise ValueError("Revision conflict or invalid variant")
            path = (self.root / user["path"]).resolve()
            if not path.is_relative_to(self.root / "src") or path.name not in (f"workstation_{identity}.cpp", f"workstation_{identity}.c"):
                raise ValueError("Refusing to remove a user source outside its managed path")
            history = self.cache_root / "history" / identity / "cpp" / f"{revision}.txt"
            history.parent.mkdir(parents=True, exist_ok=True)
            if path.exists():
                if sha256(path.read_text(encoding="utf-8").encode()) != revision:
                    raise ValueError("Managed user source changed outside revision API")
                history.write_bytes(path.read_bytes())
                path.unlink()
            del state["user_sources"][identity]
            _atomic_json(self.manifest_path, state)
            users = self._user_functions()
            users["functions"].pop(identity, None)
            _atomic_json(self.user_functions_path, users)
            return {"id": identity, "removed_revision": revision, "archived": str(history)}
        row = self._by_identity(identity, "function")
        current = state["sources"].get(row["id"], {}).get(variant)
        persisted_cpp = None
        if variant == "cpp" and current is None:
            persisted_cpp = self._persisted_cpp_binding(row["id"])
            if persisted_cpp is not None:
                current = {"path": persisted_cpp["relative"].as_posix(),
                           "revision": persisted_cpp["revision"],
                           "sha256": persisted_cpp["revision"]}
        persisted_assembly = None
        if variant == "assembly" and current is None:
            persisted_assembly = self._persisted_assembly_binding(row["id"])
            if persisted_assembly is not None:
                current = {"path": persisted_assembly["relative"].as_posix(),
                           "revision": persisted_assembly["revision"],
                           "sha256": persisted_assembly["revision"]}
        if current is None or current["revision"] != revision:
            raise ValueError("Revision conflict or source does not exist")
        # Keep immutable content under history and remove only the active pointer.
        source_path = self.root / current["path"]
        history = self.cache_root / "history" / row["id"] / f"{variant}-{revision}.txt"
        if variant == "cpp" and source_path.name not in (f"workstation_{row['id']}.cpp", f"workstation_{row['id']}.c"):
            raise ValueError("Refusing to remove a C++ file managed by source-units.json")
        history.parent.mkdir(parents=True, exist_ok=True)
        if source_path.exists():
            current_content = source_path.read_text(encoding="utf-8")
            if sha256(current_content.encode()) != current["sha256"]:
                raise ValueError("Source changed outside revision API")
            history.write_bytes(source_path.read_bytes())
            if variant != "cpp":
                source_path.unlink()
            else:
                source_path.unlink()
        source_state = state.setdefault("sources", {}).get(row["id"])
        if source_state is not None:
            source_state.pop(variant, None)
            if not source_state:
                del state["sources"][row["id"]]
        _atomic_json(self.manifest_path, state)
        if variant == "assembly":
            units = self._assembly_unit_state()
            units["units"] = [u for u in units["units"] if not (u["function_id"] == row["id"] and u["kind"] == "assembly")]
            _atomic_json(self.units_path, units)
        elif variant == "cpp":
            self._remove_cpp_unit(row["id"])
        return {"id": row["id"], "removed_revision": revision, "archived": str(history)}

    def _user_functions(self):
        if not self.user_functions_path.exists():
            return {"schema": 1, "image_sha256": (self._catalog or self._load_catalog())["image_sha256"], "functions": {}}
        doc = json.loads(self.user_functions_path.read_text(encoding="utf-8"))
        if doc.get("schema") != 1 or doc.get("image_sha256") != (self._catalog or self._load_catalog())["image_sha256"]:
            raise ValueError("New C++ units belong to a different Replay image or schema")
        return doc


