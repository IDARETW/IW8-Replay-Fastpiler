"""Conservative, source-backed model for typed native global edits.

Only fixed-size primitive arrays with exact IDA type annotations and clean
initialized-data boundaries are editable candidates. Pointers, structs,
unsized arrays, ambiguous extents, and relocated initializers remain read-only.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import sqlite3
import struct
from contextlib import closing
from pathlib import Path

import source_catalog
from workstation_sources import _atomic_json, sha256


_ARRAY_TYPES = {
    "_BYTE": (1, "unsigned char", "bytes"),
    "_QWORD": (8, "unsigned long long", "unsigned"),
    "__int64": (8, "long long", "signed"),
}
_AUTOGENERATED_GLOBAL = re.compile(r"(?:qword|dword|word|byte|unk|off|loc)_(?:0x)?[0-9a-fA-F]{6,16}\Z")


class GlobalSourceWorkspace:
    """Read/write revision records for the narrowly proven native-data subset."""

    def __init__(self, project_root, cache_root, sqlite_path=None, executable_path=None, *,
                 verify_executable=True):
        self.root = Path(project_root).resolve()
        self.cache_root = Path(cache_root).resolve()
        self.sqlite_path = Path(sqlite_path or os.environ.get("REPLAY_SQLITE") or source_catalog.database_path()).expanduser().resolve()
        game_root = Path(os.environ.get("REPLAY_GAME_ROOT", r"E:\IW8\Builds\1.20-replay")).expanduser()
        self.executable_path = Path(executable_path or os.environ.get("REPLAY_EXE") or game_root / "game_dx12_ship_replay.exe").expanduser().resolve()
        self.verify_executable = verify_executable
        self.generated = self.root / "generated"
        self._rows = None

    def _load(self):
        if self._rows is not None:
            return self._rows
        manifest = json.loads((self.generated / "manifest.json").read_text(encoding="utf-8"))
        catalog = json.loads((self.generated / "function-catalog.json").read_text(encoding="utf-8"))
        image_hash = manifest.get("input_sha256")
        if not image_hash or catalog.get("image_sha256") != image_hash:
            raise ValueError("Global catalog and generated data are not pinned to the same Replay image")
        exe_md5 = None
        if self.verify_executable:
            if not self.executable_path.is_file():
                raise ValueError(f"Pinned Replay executable is not available for global inventory verification: {self.executable_path}")
            with self.executable_path.open("rb") as source:
                exe_md5 = hashlib.file_digest(source, "md5").hexdigest()
            with self.executable_path.open("rb") as source:
                exe_sha256 = hashlib.file_digest(source, "sha256").hexdigest()
            if exe_sha256 != image_hash:
                raise ValueError("Current Replay executable does not match the generated image SHA-256")
        if not self.sqlite_path.is_file():
            raise FileNotFoundError(f"Replay IDA SQLite database not found: {self.sqlite_path}")

        with closing(sqlite3.connect(source_catalog.readonly_uri(self.sqlite_path), uri=True)) as db:
            db.execute("BEGIN")
            meta = db.execute("SELECT scope,executable_md5,total FROM replay_global_inventory_meta WHERE id=1").fetchone()
            if not meta or meta[0] != "ida-data-heads-v1" or (exe_md5 and meta[1].casefold() != exe_md5):
                raise ValueError("Native global inventory does not belong to the pinned Replay executable")
            count = db.execute("SELECT count(*) FROM replay_global_inventory").fetchone()[0]
            if count != meta[2]:
                raise ValueError("Native global inventory count does not match its recorded snapshot")
            annotations = db.execute(
                "SELECT rva,type_name FROM replay_ida_types WHERE entity_kind='global' AND locator='address'"
            ).fetchall()
            labels = {row[0]: (row[1], row[2], row[3]) for row in db.execute(
                "SELECT rva,name,segment,address FROM replay_global_inventory"
            )}
            catalog_ids = {row["rva"]: row["id"] for row in catalog.get("symbols", [])}
            heads = sorted(labels)

        sections = [(section, (self.generated / section["file"]).read_bytes())
                    for section in manifest["sections"] if section.get("file")]
        for section, data in sections:
            if hashlib.sha256(data).hexdigest() != section["sha256"]:
                raise ValueError(f"Generated section hash mismatch: {section['file']}")
        fixup_files = []
        reference_inputs = [(manifest.get("fixups_file"), manifest.get("fixups_sha256"))]
        metadata = manifest.get("metadata", {})
        reference_inputs.append((metadata.get("file"), metadata.get("sha256")))
        for filename, expected in reference_inputs:
            if not filename:
                continue
            raw = (self.generated / filename).read_bytes()
            if expected and hashlib.sha256(raw).hexdigest() != expected:
                raise ValueError(f"Generated reference table hash mismatch: {filename}")
            if len(raw) % 12:
                raise ValueError(f"Malformed reference table: {filename}")
            fixup_files.append((filename, list(struct.iter_unpack("<III", raw))))

        loader_relocations = _loader_relocations(manifest, sections)

        candidates = []
        for rva, type_name in annotations:
            parsed = _parse_finite_array(type_name)
            if parsed is None:
                continue
            count, element_size, c_type, encoding = parsed
            size = count * element_size
            label = labels.get(rva)
            identity = catalog_ids.get(rva)
            if not label or not identity or size <= 0:
                continue
            database_name, segment, _address = label
            from recovered_cpp_names import global_name, DATA_PLACEHOLDER
            name = (global_name(rva, manifest['image_base']) if not database_name or
                    DATA_PLACEHOLDER.fullmatch(database_name) else database_name)
            section_data = next(((section, data) for section, data in sections
                                 if section["rva"] <= rva and
                                 rva + size <= section["rva"] + max(section["raw_size"], section["virtual_size"])), None)
            if not section_data:
                continue
            section, data = section_data
            if segment != section["name"] or section["name"] not in (".data", ".rdata"):
                continue
            data_offset = rva - section["rva"]
            if any(rva < head < rva + size for head in heads):
                continue
            hits = [(file, at - rva, target, width) for file, fixups in fixup_files
                    for at, target, width in fixups if rva <= at < rva + size]
            loader_hits = [(at - rva, kind) for at, kind in loader_relocations if rva <= at < rva + size]
            if hits or loader_hits:
                continue
            raw_end = min(data_offset + size, len(data))
            original = data[data_offset:raw_end]
            if len(original) < size:
                if data_offset < len(data) or data_offset + size > section["virtual_size"]:
                    continue
                original += bytes(size - len(original))
            if len(original) != size:
                continue
            alignment = 1 << min((rva & -rva).bit_length() - 1, 4) if rva else 1
            if rva % min(alignment, element_size):
                continue
            revision = _revision(image_hash, identity, type_name, original)
            candidates.append({
                "id": identity, "name": name or identity, "rva": rva,
                "segment": section["name"], "type_name": type_name,
                "element_count": count, "element_size": element_size,
                "size": size, "alignment": min(alignment, element_size),
                "c_type": c_type, "encoding": encoding,
                "original_bytes": original, "revision": revision,
                "section_file": section["file"], "section_offset": data_offset,
                "section_raw_size": section["raw_size"],
                "file_alignment": int(manifest["optional"]["FileAlignment"]),
                "storage": "initialized" if data_offset + size <= len(data) else "zero-initialized BSS",
                "reference_free": True,
                "loader_relocation_free": True,
                "provenance": {"basis": "Replay SQLite global type annotation + exact initialized section range",
                               "database_name": database_name,
                               "sqlite_executable_md5": exe_md5, "image_sha256": image_hash,
                               "interior_global_heads": 0, "interior_fixups": 0,
                               "type_confidence": "IDA annotation; primitive fixed-size array only"},
            })
        self._rows = {row["id"]: row for row in candidates}
        self._manifest = manifest
        return self._rows

    def load_build_overrides(self):
        """Read revision-checked typed overrides without opening the game image."""
        rows = self._load()
        override_root = self.cache_root / "globals"
        if not override_root.is_dir():
            return []
        result = []
        for path in sorted(override_root.glob("sym_*.json")):
            identity = path.stem
            row = rows.get(identity)
            if row is None:
                raise ValueError(f"Saved global override has no proven typed inventory owner: {identity}")
            document = json.loads(path.read_text(encoding="utf-8"))
            if (document.get("schema") != 1 or document.get("image_sha256") != self._manifest["input_sha256"] or
                    document.get("identity") != identity or document.get("type_name") != row["type_name"] or
                    document.get("original_revision") != row["revision"]):
                raise ValueError(f"Global override provenance or native type changed: {identity}")
            payload = _encode_values(row, document.get("values"))
            revision = _revision(self._manifest["input_sha256"], identity, row["type_name"], payload)
            if document.get("revision") != revision or document.get("initializer_sha256") != sha256(payload):
                raise ValueError(f"Global override revision/hash mismatch: {identity}")
            result.append({"id": identity, "name": row["name"], "source_rva": row["rva"],
                           "section": row["segment"], "size": row["size"],
                           "section_offset": row["section_offset"],
                           "section_raw_size": row["section_raw_size"],
                           "file_alignment": row["file_alignment"],
                           "type_name": row["type_name"], "original_revision": row["revision"],
                           "revision": revision, "before_sha256": sha256(row["original_bytes"]),
                           "before_data": row["original_bytes"], "data": payload,
                           "estimated_file_growth_bytes": _estimate_file_growth(row, payload),
                           "source": str(path)})
        return result
    def list_editable(self):
        rows = self._load()
        return [{key: value for key, value in row.items() if key != "original_bytes"}
                for row in sorted(rows.values(), key=lambda item: (item["name"].casefold(), item["id"]))]

    def get_source(self, identity):
        row = self._load().get(identity)
        if row is None:
            raise KeyError("Global has no proven fixed-size primitive initializer extent")
        override_path = self._override_path(identity)
        if override_path.is_file():
            override = json.loads(override_path.read_text(encoding="utf-8"))
            if override.get("image_sha256") != self._manifest["input_sha256"] or override.get("original_revision") != row["revision"]:
                raise ValueError("Global override belongs to a different image or original data revision")
            values = override["values"]
            revision = override["revision"]
        else:
            values = _decode_values(row)
            revision = row["revision"]
        payload = _encode_values(row, values)
        if _revision(self._manifest["input_sha256"], identity, row["type_name"], payload) != revision:
            raise ValueError("Global initializer revision does not match its typed bytes")
        public_values = values if row["encoding"] == "bytes" else [str(value) for value in values]
        content = json.dumps({"type_name": row["type_name"], "values": public_values}, indent=2) + "\n"
        return {key: value for key, value in row.items() if key != "original_bytes"} | {
            "variant": "global-initializer", "language": "json",
            "values": public_values, "content": content,
            "revision": revision, "editable": True, "compilable": True,
            "compilation_limit": None,
            "estimated_file_growth_bytes": _estimate_file_growth(row, payload),
        }

    def save_source(self, identity, values, revision):
        row = self._load().get(identity)
        if row is None:
            raise KeyError("Global has no proven fixed-size primitive initializer extent")
        current = self.get_source(identity)
        if revision != current["revision"]:
            raise ValueError("Revision conflict; reopen the current global source before saving")
        if isinstance(values, str):
            try:
                document = json.loads(values)
            except json.JSONDecodeError as error:
                raise ValueError("Global initializer content must be valid JSON") from error
            if isinstance(document, dict):
                if document.get("type_name") != row["type_name"]:
                    raise ValueError("Global initializer content cannot change the native annotated type")
                values = document.get("values")
            else:
                values = document
        payload = _encode_values(row, values)
        new_revision = _revision(self._manifest["input_sha256"], identity, row["type_name"], payload)
        document = {"schema": 1, "image_sha256": self._manifest["input_sha256"],
                    "identity": identity, "name": row["name"], "type_name": row["type_name"],
                    "original_revision": row["revision"], "revision": new_revision,
                    "values": values, "initializer_sha256": sha256(payload),
                    "provenance": row["provenance"]}
        _atomic_json(self._override_path(identity), document)
        return self.get_source(identity)

    def restore_source(self, identity, revision):
        """Archive the active edit and restore the pinned original initializer."""
        row = self._load().get(identity)
        if row is None:
            raise KeyError("Global has no proven fixed-size primitive initializer extent")
        current = self.get_source(identity)
        if current["revision"] != revision:
            raise ValueError("Revision conflict; reopen the current global source before restoring")
        path = self._override_path(identity)
        if not path.is_file():
            return current
        document = json.loads(path.read_text(encoding="utf-8"))
        if document.get("revision") != revision:
            raise ValueError("Saved global edit changed outside the revision API")
        history = self.cache_root / "history" / "globals" / identity / f"{revision}.json"
        history.parent.mkdir(parents=True, exist_ok=True)
        original = path.read_bytes()
        if history.exists() and history.read_bytes() != original:
            raise ValueError("Global revision archive already exists with different contents")
        if not history.exists():
            history.write_bytes(original)
        path.unlink()
        restored = self.get_source(identity)
        return restored | {"restored": True, "archived": str(history)}

    def render_cpp(self, identity):
        source = self.get_source(identity)
        row = self._load()[identity]
        values = source["values"]
        name = row["id"]
        ctype = row["c_type"]
        if row["encoding"] == "bytes":
            initializer = ", ".join(f"0x{value:02x}" for value in values)
        elif row["encoding"] == "unsigned":
            initializer = ", ".join(f"0x{value:016x}ULL" for value in values)
        else:
            initializer = ", ".join(f"{value}LL" for value in values)
        return ("#include <cstdint>\nextern \"C\" {\n"
                f"alignas({row['alignment']}) {ctype} {name}[{row['element_count']}] = "
                f"{{{initializer}}};\n}}\n"
                f"static_assert(sizeof({name}) == {row['size']});\n")

    def _override_path(self, identity):
        if not re.fullmatch(r"sym_[0-9a-f]{16}", identity):
            raise ValueError("Global source identity must be a stable catalog symbol ID")
        return self.cache_root / "globals" / f"{identity}.json"


def apply_global_overrides(sections, overrides, layout, replacements):
    """Apply exact-size, reference-free initializer edits to their mapped section.

    The data stays at its original owner/extent, so no other object or PE data
    directory changes size. Existing code/data relocations already use the
    same layout map; global candidates with pointer/fixup fields are excluded
    during inventory discovery.
    """
    reports = []
    applied_ranges = []
    for item in overrides:
        source_rva, size = item["source_rva"], item["size"]
        if any(source_rva < replacement["end"] and source_rva + size > replacement["begin"]
               for replacement in replacements):
            raise ValueError(f"Global initializer overlaps a replaced function: {item['id']}")
        mapped_begin, mapped_end = layout.map(source_rva), layout.map(source_rva + size)
        if mapped_end - mapped_begin != size:
            raise ValueError(f"Global initializer extent was split by the new layout: {item['id']}")
        if any(mapped_begin < end and mapped_end > begin for begin, end in applied_ranges):
            raise ValueError(f"Global initializer overrides overlap: {item['id']}")
        section = next((row for row in sections if row["name"] == item["section"]), None)
        if section is None:
            raise ValueError(f"Global initializer owner section is missing: {item['section']}")
        offset = mapped_begin - section["rva"]
        if offset < 0 or offset + size > section["virtual_size"]:
            raise ValueError(f"Mapped global initializer falls outside its PE section: {item['id']}")
        data = section["data"]
        available = max(0, min(size, len(data) - offset))
        current = bytes(data[offset:offset+available])
        original = item["before_data"]
        if len(original) != size or current != original[:available] or any(original[available:]):
            raise ValueError(f"Original bytes differ from the pinned global initializer: {item['id']}")
        payload = item["data"]
        if len(payload) != size:
            raise ValueError(f"Global initializer changed its proven native extent: {item['id']}")
        if any(payload[available:]):
            data.extend(bytes(offset + size - len(data)))
        if any(payload):
            data[offset:offset+size] = payload
        applied_ranges.append((mapped_begin, mapped_end))
        reports.append({"id": item["id"], "name": item["name"],
                        "source_rva": source_rva, "mapped_rva": mapped_begin,
                        "section": item["section"], "size": size, "type_name": item["type_name"],
                        "original_revision": item["original_revision"], "revision": item["revision"],
                        "before_sha256": item["before_sha256"], "after_sha256": sha256(payload),
                        "source": item["source"], "in_place": True,
                        "section_growth": max(0, len(data) - section["raw_size"]),
                        "estimated_file_growth_bytes": max(
                            0, _align(len(data), item["file_alignment"])
                            - _align(section["raw_size"], item["file_alignment"])),
                        "changed": payload != original})
    return reports


def _parse_finite_array(type_name):
    match = re.fullmatch(r"(_BYTE|_QWORD|__int64)\[(\d+)\]", type_name.strip())
    if not match:
        return None
    element_type, count_text = match.groups()
    count = int(count_text)
    if count <= 0 or count > 1_000_000:
        return None
    element_size, c_type, encoding = _ARRAY_TYPES[element_type]
    return count, element_size, c_type, encoding


def _revision(image_hash, identity, type_name, payload):
    return sha256((image_hash + ":" + identity + ":" + type_name + ":").encode() + payload)


def _align(value, alignment):
    return (value + alignment - 1) & -alignment


def _estimate_file_growth(row, payload):
    if row["storage"] != "zero-initialized BSS" or not any(payload):
        return 0
    required_end = row["section_offset"] + row["size"]
    alignment = row["file_alignment"]
    return max(0, _align(required_end, alignment) - _align(row["section_raw_size"], alignment))


def _loader_relocations(manifest, sections):
    """Decode PE base relocations so opaque pointer words are never edited."""
    directories = manifest.get("directories", [])
    if len(directories) <= 5:
        raise ValueError("Generated PE manifest has no base-relocation directory")
    rva, size = directories[5]["rva"], directories[5]["size"]
    if not rva or not size:
        return []
    data = None
    for section, payload in sections:
        offset = rva - section["rva"]
        if offset >= 0 and offset + size <= len(payload):
            data = payload[offset:offset + size]
            break
    if data is None:
        raise ValueError("Base-relocation directory is outside recovered initialized section bytes")
    result = []
    cursor = 0
    while cursor < len(data):
        if cursor + 8 > len(data):
            raise ValueError("Truncated base-relocation block")
        page_rva, block_size = struct.unpack_from("<II", data, cursor)
        if block_size < 8 or block_size & 1 or cursor + block_size > len(data):
            raise ValueError("Invalid base-relocation block size")
        for (entry,) in struct.iter_unpack("<H", data[cursor + 8:cursor + block_size]):
            kind, offset = entry >> 12, entry & 0xFFF
            if kind:
                result.append((page_rva + offset, kind))
        cursor += block_size
    return result


def _decode_values(row):
    data = row["original_bytes"]
    count, size, kind = row["element_count"], row["element_size"], row["encoding"]
    if kind == "bytes":
        return list(data)
    signed = kind == "signed"
    return [int.from_bytes(data[i * size:(i + 1) * size], "little", signed=signed) for i in range(count)]


def _encode_values(row, values):
    if not isinstance(values, list) or len(values) != row["element_count"]:
        raise ValueError("Initializer must preserve the proven element count")
    result = bytearray()
    size, kind = row["element_size"], row["encoding"]
    for value in values:
        if isinstance(value, str) and kind != "bytes" and re.fullmatch(r"-?(?:0|[1-9][0-9]*)", value):
            value = int(value, 10)
        if isinstance(value, bool) or not isinstance(value, int):
            raise ValueError("Primitive global initializers accept exact decimal string or integer elements")
        if kind == "bytes":
            if not 0 <= value <= 0xff:
                raise ValueError("_BYTE element is outside the 0..255 range")
            result.append(value)
        else:
            try:
                result.extend(value.to_bytes(size, "little", signed=(kind == "signed")))
            except OverflowError as error:
                raise ValueError("64-bit global initializer element is outside its signed/unsigned range") from error
    if len(result) != row["size"]:
        raise ValueError("Initializer does not match the proven native extent")
    return bytes(result)
